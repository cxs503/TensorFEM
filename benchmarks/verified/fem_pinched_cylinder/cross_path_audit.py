#!/usr/bin/env python3
"""Cross-path audit: do the two independent code paths for the pinched cylinder agree?

Why this exists
---------------
The same benchmark case (MacNeal-Harder pinched cylinder, symmetry octant, unit
pair of diametrically opposed loads) is solved in this repository by *two*
independent code paths:

``A  tensorfem.pinched_cylinder``            the anchor path --
   ``pinched_cylinder_model`` + ``cylindrical_shell4_stiffness``, driven by
   ``run_verification.py`` (certificate) and by ``run.py`` (case evidence);
``B  tensorfem.shell_benchmark_suite``       the main-solver path --
   ``pinched_cylinder_case()`` + ``benchmark_cases.run_case``, driven by the
   platform case registry.

Both claim the same quantity against the same published reference
(-1.8248e-5 in, MacNeal & Harder 1985).  If they disagree, the anchor is
certifying a model that the production path does not use -- or one of the two
models is wrong.  That is a provenance question with an exact answer: run both
ladders and compare, no physics judgement required.

Measured (see ``cross_path_audit.json``, regenerated by this script):

* path B reaches 2.86 % at 4x4 and 0.99 % at 12x12;
* path A reads -2.66e-6 in at 4x4 -- **85 % low**, i.e. ~6.7x stiffer -- and
  only approaches the reference on very fine rungs (16 % at 32x32).

The committed case evidence (``case_result.json``: 0.167 % at 16x16) matches
path B, so the numbers in the evidence are the ones path B produces, while the
anchor's own ``result.json`` (85 % -> 16 %) is what path A produces.  Two files
in the same directory describe the same case with different physics.

Falsified hypothesis (recorded, so it is not re-tried)
-----------------------------------------------------
The octant constraint set at the circumferential reflection planes looked wrong
(``w``-constrained at theta=pi/2 instead of the tangential ``v``): on a mirror
plane with unit normal m the normal translation and the in-plane rotations
vanish, and at theta=pi/2 the local triad is t=-z, n=y, so symmetry of the plane
z=0 requires u_z = -v = 0, not u_y = 0.  Fixing that (constrain {v, r_x}
instead of {w, r_x, r_t}) changes the 4x4 reading by 2.9 %
(-2.656e-6 -> -2.580e-6 in), i.e. it is **not** the cause of the 6.7x gap.  The
hypothesis is therefore deferred, not shipped.

Usage
-----
    PYTHONPATH=src python benchmarks/verified/fem_pinched_cylinder/cross_path_audit.py
    # writes cross_path_audit.json (+ cross_path_audit.png) next to this file
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import torch

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
sys.path.insert(0, str(REPO / "src"))

import matplotlib  # noqa: E402

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

from tensorfem.benchmark_cases import run_case  # noqa: E402
from tensorfem.pinched_cylinder import (  # noqa: E402
    REFERENCE_DISPLACEMENT,
    solve_pinched_cylinder_sparse,
)
from tensorfem.shell_benchmark_suite import pinched_cylinder_case  # noqa: E402

#: rungs both paths can afford in one short run; the finer rungs of the
#: anchor ladder (24x24, 32x32) are already published in result.json.
MESHES = (3, 4, 6, 8, 12, 16)


def relative_error(value: float) -> float:
    return abs(value / REFERENCE_DISPLACEMENT - 1.0)


def _which_path(committed_match: dict, tol: float = 1e-9) -> str:
    """Name the path the committed evidence reproduces (``neither`` if no match).

    Only rungs that both paths actually computed are compared; a rung the
    committed ladder has but path B never ran carries no information.
    """
    for key in ("path_b", "path_a"):
        rel_key = "vs_" + key + "_rel"
        comparable = [v[rel_key] for v in committed_match.values() if v.get(rel_key) is not None]
        if comparable and max(comparable) < tol:
            return key
    return "neither"


def main() -> int:
    suite = run_case(pinched_cylinder_case())
    path_b = {r["mesh"]: r["computed"] for r in suite["results"]}

    path_a = {}
    for n in MESHES:
        path_a[n] = solve_pinched_cylinder_sparse(n).displacement
        print(f"  path A n={n:2d}: {path_a[n]:+.6e} in  err={relative_error(path_a[n]) * 100:7.3f}%",
              flush=True)

    rows = []
    for n in sorted(set(path_a) & set(path_b)):
        a, b = path_a[n], path_b[n]
        rows.append({
            "mesh": f"{n}x{n}",
            "n": n,
            "path_a_anchor_in": a,
            "path_a_error_pct": relative_error(a) * 100.0,
            "path_b_suite_in": b,
            "path_b_error_pct": relative_error(b) * 100.0,
            "ratio_b_over_a": b / a,
            "relative_disagreement": abs(a / b - 1.0),
        })

    committed = json.loads((HERE / "case_result.json").read_text())
    committed_levels = {l["n"]: l["displacement_in"] for l in committed["levels"]}
    committed_match = {
        str(n): {
            "committed_in": committed_levels[n],
            "vs_path_a_rel": abs(committed_levels[n] / path_a[n] - 1.0) if n in path_a else None,
            "vs_path_b_rel": abs(committed_levels[n] / path_b[n] - 1.0) if n in path_b else None,
        }
        for n in sorted(committed_levels)
    }

    payload = {
        "schema": "tensorfem.cross-path-audit/1",
        "case": "CASE-FEM-PINCHED-CYLINDER",
        "question": "do the anchor path (A) and the main-solver path (B) solve the same model?",
        "reference": {
            "value_in": REFERENCE_DISPLACEMENT,
            "source": "MacNeal & Harder (1985)",
        },
        "path_a": {
            "modules": ["tensorfem.pinched_cylinder.pinched_cylinder_model",
                        "tensorfem.cylindrical_shell4.cylindrical_shell4_stiffness"],
            "drivers": ["benchmarks/verified/fem_pinched_cylinder/run_verification.py",
                        "benchmarks/verified/fem_pinched_cylinder/run.py"],
        },
        "path_b": {
            "modules": ["tensorfem.shell_benchmark_suite.pinched_cylinder_case",
                        "tensorfem.benchmark_cases.run_case"],
            "drivers": ["platform case registry (run_case)"],
        },
        "rows": rows,
        "committed_case_evidence_alignment": committed_match,
        "verdict": {
            "agreement": bool(rows and all(r["relative_disagreement"] < 1e-6 for r in rows)),
            "max_disagreement": max((r["relative_disagreement"] for r in rows), default=None),
            "committed_evidence_matches": _which_path(committed_match),
            "statement": (
                "The two paths do not solve the same discrete model: the anchor path is "
                "quantitatively stiff on every rung that both paths share, and the case "
                "evidence already committed in this directory reproduces the main-solver "
                "path, not the anchor path."
            ),
        },
        "falsified_hypothesis": {
            "claim": "the theta=pi/2 octant constraint set (w instead of v) explains the gap",
            "test": "constrain {v, r_x} on the theta=pi/2 plane and re-read 4x4",
            "result_before_in": -2.656165677507929e-06,
            "result_after_in": -2.5801983860e-06,
            "change_pct": 2.9,
            "verdict": "falsified - the constraint fix moves the reading 2.9%, not 670%",
        },
        "open_questions": [
            "which of the two models carries the correct diaphragm/symmetry semantics "
            "(the published reference separates them by ~0.4% at 12x12: path B 0.99%)",
            "why path A converges so slowly (16% at 32x32) while path B is at 1.4% by 3x3",
            "the anchor certificate and the case evidence must be re-emitted from one path "
            "once the disagreement is resolved",
        ],
    }

    out = HERE / "cross_path_audit.json"
    out.write_text(json.dumps(payload, indent=2) + "\n")
    print(f"\n  wrote {out}")

    fig, ax = plt.subplots(figsize=(7, 4.8))
    ns_a = [r["n"] for r in rows]
    ax.loglog(ns_a, [r["path_a_error_pct"] for r in rows], "o-", lw=2, ms=7,
              label="path A: tensorfem.pinched_cylinder (anchor)")
    ax.loglog(ns_a, [r["path_b_error_pct"] for r in rows], "s--", lw=2, ms=7,
              label="path B: shell_benchmark_suite (main solver)")
    ax.axhline(3.0, color="red", ls=":", lw=1.2, label="3% gate")
    ax.set_xlabel("N (elements per octant side)")
    ax.set_ylabel("|u$_N$/u$_{ref}$ - 1| (%)")
    ax.set_title("Pinched cylinder: the same case, two code paths")
    ax.grid(True, which="both", alpha=0.3)
    ax.set_xticks(ns_a)
    ax.set_xticklabels([str(n) for n in ns_a])
    ax.legend(fontsize=8)
    fig.tight_layout()
    fig.savefig(HERE / "cross_path_audit.png", dpi=150)
    plt.close(fig)
    print(f"  wrote {HERE / 'cross_path_audit.png'}")
    print(f"  agreement={payload['verdict']['agreement']} "
          f"max_disagreement={payload['verdict']['max_disagreement']:.3e} "
          f"committed_evidence_matches={payload['verdict']['committed_evidence_matches']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())