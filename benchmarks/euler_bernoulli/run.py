def _pct(value: float, digits: int = 3) -> str:
    return f"{100.0 * value:+.{digits}f}%"


def convergence_block(results: dict) -> str:
    """Markdown convergence tables, generated from the JSON of this run."""
    beam, plate, half = results["beam"], results["plate"], results["halfspace"]
    lines = [
        BEGIN,
        "",
        "Numbers below are generated by `benchmarks/euler_bernoulli/run.py`",
        "(`docs/FEM_VERIFY.md` prose is hand-written; this block is not).",
        "",
        "#### Table 1 - Euler-Bernoulli cantilever tip deflection (L/h = 100)",
        "",
        f"Analytic `{beam['analytic']['formula']}` = "
        f"{beam['analytic']['tip_deflection']:.6e} m.",
        "",
        "| discretisation | level | dofs | tip deflection [m] | relative error |",
        "|---|---|---|---|---|",
    ]
    for row in beam["frame_levels"]:
        lines.append(f"| frame2d BE | {row['n_elements']} elements | {row['dofs']} | "
                     f"{row['tip_deflection']:.6e} | {_pct(row['relative_error'])} |")
    for row in beam["solid_levels"]:
        lines.append(f"| HEX20 3-D solid | {row['axial_elements']} axial x "
                     f"{row['cross_elements']}^2 cross | {row['dofs']} | "
                     f"{row['tip_deflection']:.6e} | {_pct(row['relative_error'])} |")

    lines += [
        "",
        "#### Table 2 - Thin SS square plate centre deflection (a/t = 100, uniform pressure)",
        "",
        f"Reference: Navier series `w_c = {plate['reference']['centre_deflection']:.6e}` m "
        f"(coefficient {plate['reference']['centre_coefficient']:.6f}; the textbook "
        f"0.00406 sits "
        f"{_pct((plate['reference']['centre_coefficient'] - 0.00406) / 0.00406, 3)} from it).",
        "",
        "| level | elements | dofs | centre deflection [m] | coefficient | relative error |",
        "|---|---|---|---|---|---|",
    ]
    for row in plate["levels"]:
        lines.append(f"| n = {row['elements_per_side']} | {row['elements']} | {row['dofs']} | "
                     f"{row['centre_deflection']:.6e} | {row['coefficient']:.6f} | "
                     f"{_pct(row['relative_error'])} |")

    lines += [
        "",
        "#### Table 3 - Boussinesq half-space centre settlement, 2a x 2a loaded patch",
        "",
        "| level | box lateral x depth [a] | elements | free dofs | w_centre [m] | "
        "w exact [m] | relative error | reaction balance |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for row in half["levels"]:
        lines.append(
            f"| {row['level']} | {row['lateral_extent_in_patch_widths']:.0f} x "
            f"{row['depth_extent_in_patch_widths']:.0f} | {row['elements']} | "
            f"{row['free_dofs']} | {row['w_centre']:.6e} | {row['w_centre_exact']:.6e} | "
            f"{_pct(row['relative_error'])} | {row['reaction_balance_rel']:.1e} |")

    lines += [
        "",
        "#### Table 4 - Machine criteria",
        "",
        "| criterion | limit | measured | verdict |",
        "|---|---|---|---|",
        f"| cantilever tip deflection | 3% | {_pct(beam['finest_relative_error'], 2)} | "
        f"{'PASS' if beam['passed'] else 'FAIL'} |",
        f"| thin-plate centre deflection | 5% | {_pct(plate['finest_relative_error'], 2)} | "
        f"{'PASS' if plate['passed'] else 'FAIL'} |",
        f"| Boussinesq centre displacement | 5% | {_pct(half['finest_relative_error'], 2)} | "
        f"{'PASS' if half['passed'] else 'FAIL'} |",
        f"| two-level refinement, all three cases | >= 2 levels, monotone | "
        f"beam {beam['refinement']['levels']}, plate {plate['refinement']['levels']}, "
        f"half-space {half['refinement']['levels']} levels; monotone = "
        f"{beam['refinement']['non_increasing'] and plate['refinement']['non_increasing'] and half['refinement']['non_increasing']} | "
        f"{'PASS' if results['verdict']['convergence'] else 'FAIL'} |",
        "",
        END,
    ]
    return "\n".join(lines)


def inject_doc(results: dict) -> bool:
    """Replace the generated block of ``docs/FEM_VERIFY.md`` with fresh tables."""
    block = convergence_block(results)
    if not DOC.exists():
        return False
    text = DOC.read_text(encoding="utf-8")
    if BEGIN not in text or END not in text:
        return False
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    DOC.write_text(head + block + tail, encoding="utf-8")
    return True


