BEAM = dict(young=200.0e9, poisson=0.3, length=1.0, width=0.01, height=0.01, load=5.0)


def beam_analytic(cfg: dict = BEAM) -> dict:
    """Euler-Bernoulli tip deflection and rotation of an end-loaded cantilever."""
    inertia = cfg["width"] * cfg["height"] ** 3 / 12.0
    tip = cfg["load"] * cfg["length"] ** 3 / (3.0 * cfg["young"] * inertia)
    return {
        "formula": "delta = P L^3 / (3 E I),  I = b h^3 / 12",
        "inertia": inertia,
        "slenderness": cfg["length"] / cfg["height"],
        "tip_deflection": tip,
        "tip_rotation": cfg["load"] * cfg["length"] ** 2 / (2.0 * cfg["young"] * inertia),
    }


def beam_frame_levels(level_elements=(10, 20, 40), cfg: dict = BEAM) -> list[dict]:
    """Cantilever modelled with cubic-Hermite Euler-Bernoulli frame elements."""
    analytic = beam_analytic(cfg)["tip_deflection"]
    area = cfg["width"] * cfg["height"]
    inertia = cfg["width"] * cfg["height"] ** 3 / 12.0
    rows = []
    for n in level_elements:
        started = time.perf_counter()
        nodes = torch.stack(
            (torch.linspace(0.0, cfg["length"], n + 1, dtype=DTYPE),
             torch.zeros(n + 1, dtype=DTYPE)), dim=1)
        elements = torch.stack((torch.arange(n), torch.arange(1, n + 1)), dim=1)
        forces = torch.zeros(3 * (n + 1), dtype=DTYPE)
        forces[3 * n + 1] = -cfg["load"]                     # transverse tip load
        model = FrameModel(
            nodes=nodes, elements=elements,
            young_modulus=torch.tensor([cfg["young"]], dtype=DTYPE),
            area=torch.tensor([area], dtype=DTYPE),
            inertia=torch.tensor([inertia], dtype=DTYPE),
            forces=forces,
            fixed_dofs=torch.tensor([0, 1, 2]),              # clamp node 0
        )
        result = solve_frame_static(model)
        tip = -float(result.displacement[3 * n + 1])
        rows.append({
            "n_elements": n,
            "dofs": int(model.n_dofs),
            "tip_deflection": tip,
            "relative_error": (tip - analytic) / analytic,
            "seconds": time.perf_counter() - started,
        })
    return rows


def beam_solid_levels(levels=((10, 2), (20, 2), (20, 4)), cfg: dict = BEAM) -> list[dict]:
    """Same bar as a 3-D HEX20 solid: an actual h-ladder onto beam theory."""
    analytic = beam_analytic(cfg)["tip_deflection"]
    rows = []
    for n_axial, n_cross in levels:
        started = time.perf_counter()
        nodes, cells = structured_hex20_mesh(
            cfg["length"], cfg["width"], cfg["height"], n_axial, n_cross, n_cross,
            dtype=DTYPE)
        right = torch.where(nodes[:, 0] == cfg["length"])[0]
        forces = torch.zeros(3 * len(nodes), dtype=DTYPE)
        forces[3 * right + 2] = -cfg["load"] / len(right)    # resultant over the tip face
        left = torch.where(nodes[:, 0] == 0.0)[0]
        fixed = torch.stack((3 * left, 3 * left + 1, 3 * left + 2), dim=1).reshape(-1)
        result = solve_hex20(Hex20Model(
            nodes=nodes, elements=cells,
            young_modulus=torch.tensor(cfg["young"], dtype=DTYPE),
            poisson_ratio=torch.tensor(cfg["poisson"], dtype=DTYPE),
            forces=forces, fixed_dofs=fixed))
        tip = -float(result.displacement[3 * right + 2].mean())
        rows.append({
            "axial_elements": n_axial,
            "cross_elements": n_cross,
            "nodes": int(len(nodes)),
            "dofs": int(3 * len(nodes)),
            "tip_deflection": tip,
            "relative_error": (tip - analytic) / analytic,
            "seconds": time.perf_counter() - started,
        })
    return rows


# --------------------------------------------------------------------------- #
# 2. Thin simply-supported square plate under uniform pressure
# --------------------------------------------------------------------------- #
PLATE = dict(side=1.0, thickness=0.01, young=200.0e9, poisson=0.3, pressure=1.0e3)


def plate_navier_series(cfg: dict = PLATE, terms: int = 399) -> dict:
    """Navier double series for the centre deflection of an SS square plate.

    ``w(a/2,a/2) = (16 q a^4)/(pi^6 D) * sum_{m,n odd} sin(m pi/2) sin(n pi/2)
    / (m n (m^2+n^2)^2)`` -- evaluated here, so the reference is not copied from
    a table.  The textbook coefficient 0.00406 is kept as a second anchor.
    """
    side, t, e, nu, q = (cfg["side"], cfg["thickness"], cfg["young"],
                         cfg["poisson"], cfg["pressure"])
    rigidity = e * t ** 3 / (12.0 * (1.0 - nu ** 2))
    total = math.fsum(
        math.sin(m * math.pi / 2) * math.sin(n * math.pi / 2)
        / (m * n * (m * m + n * n) ** 2)
        for m in range(1, terms + 1, 2)
        for n in range(1, terms + 1, 2)
    )
    centre = 16.0 * q * side ** 4 / (math.pi ** 6 * rigidity) * total
    return {
        "formula": "Navier series, SS square plate, uniform load (399x399 odd terms)",
        "rigidity": rigidity,
        "centre_deflection": centre,
        "centre_coefficient": centre * rigidity / (q * side ** 4),
        "timoshenko_coefficient": 0.00406,
        "timoshenko_centre_deflection": 0.00406 * q * side ** 4 / rigidity,
        "aspect_ratio": side / t,
    }


def _plate_uniform(n: int, cfg: dict,
                   shear_treatment: str = "sri") -> tuple[float, torch.Tensor, torch.Tensor]:
    """Q4 Mindlin SS plate under uniform pressure; returns (centre w, nodes, w field)."""
    side, t = cfg["side"], cfg["thickness"]
    nodes, elements = structured_square_mesh(n, side, dtype=DTYPE)
    ndof = 3 * nodes.shape[0]
    K = torch.zeros((ndof, ndof), dtype=DTYPE)
    f = torch.zeros(ndof, dtype=DTYPE)
    gp = 1.0 / 3.0 ** 0.5
    for conn in elements:
        xy = nodes[conn]
        ke = q4_mindlin_stiffness(xy, cfg["young"], cfg["poisson"], t,
                                  shear_treatment=shear_treatment)
        fe = torch.zeros(12, dtype=DTYPE)
        for xi_value in (-gp, gp):
            for eta_value in (-gp, gp):
                N, dN_nat = _shape(nodes.new_tensor(xi_value), nodes.new_tensor(eta_value))
                jac = dN_nat.T @ xy
                fe[0::3] += N * cfg["pressure"] * torch.linalg.det(jac)
        dofs = torch.stack((3 * conn, 3 * conn + 1, 3 * conn + 2), dim=1).reshape(-1)
        K[dofs[:, None], dofs] += ke
        f[dofs] += fe
    tol = side * 1e-12
    x_edge = (nodes[:, 0].abs() < tol) | ((nodes[:, 0] - side).abs() < tol)
    y_edge = (nodes[:, 1].abs() < tol) | ((nodes[:, 1] - side).abs() < tol)
    edge = x_edge | y_edge
    # hard simple support: w = 0 and the tangential rotation vanishes on the edge
    fixed = torch.cat((
        3 * torch.nonzero(edge, as_tuple=False).flatten(),
        3 * torch.nonzero(y_edge, as_tuple=False).flatten() + 1,
        3 * torch.nonzero(x_edge, as_tuple=False).flatten() + 2,
    )).unique()
    all_dofs = torch.arange(ndof)
    free = all_dofs[~torch.isin(all_dofs, fixed)]
    u = torch.zeros(ndof, dtype=DTYPE)
    u[free] = torch.linalg.solve(K[free[:, None], free], f[free])
    centre = int(torch.argmin(((nodes - nodes.new_tensor([side / 2, side / 2])) ** 2).sum(1)))
    return float(u[3 * centre]), nodes, u[0::3]


def plate_levels(side_elements=(8, 16, 24), cfg: dict = PLATE) -> tuple[list[dict], dict]:
    reference = plate_navier_series(cfg)
    rows, field = [], None
    scale = cfg["pressure"] * cfg["side"] ** 4
    for n in side_elements:
        started = time.perf_counter()
        centre, nodes, w = _plate_uniform(n, cfg)
        rows.append({
            "elements_per_side": n,
            "elements": n * n,
            "dofs": int(3 * nodes.shape[0]),
            "centre_deflection": centre,
            "relative_error": (centre - reference["centre_deflection"]) / reference["centre_deflection"],
            "coefficient": centre * reference["rigidity"] / scale,
            "seconds": time.perf_counter() - started,
        })
        if n == max(side_elements):
            field = (nodes.clone(), w.clone())
    # independent shear treatment on the coarsest level: the ladder must not be an
    # artefact of the selective-reduced-integration trick
    mitc_centre, _, _ = _plate_uniform(min(side_elements), cfg, shear_treatment="mitc")
    cross = {
        "level": min(side_elements),
        "shear_treatment": "mitc",
        "centre_deflection": mitc_centre,
        "relative_error": (mitc_centre - reference["centre_deflection"]) / reference["centre_deflection"],
        "sri_relative_error": rows[0]["relative_error"],
        "difference_sri_vs_mitc": abs(mitc_centre - rows[0]["centre_deflection"]) / rows[0]["centre_deflection"],
    }
    return rows, {"reference": reference, "field": field, "shear_cross_check": cross}


