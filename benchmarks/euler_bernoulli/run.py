HALFSPACE = dict(young=1.0e6, poisson=0.3, pressure=1.0e3, half_width=1.0)

# (label, lateral, depth, n_fine, n_grow, nz_layers) -- extents in units of a
HALFSPACE_LEVELS = (
    ("mesh-1 box-20", 20.0, 20.0, 4, 10, 14),
    ("mesh-2 box-20", 20.0, 20.0, 4, 20, 20),
    ("mesh-2 box-30", 30.0, 25.0, 4, 20, 18),
    ("mesh-2 box-40", 40.0, 30.0, 4, 24, 20),
)


@dataclass(frozen=True)
class HalfSpaceSolution:
    displacement: torch.Tensor
    nodes: torch.Tensor
    axes: tuple[int, int, int]
    n_elements: int
    n_dofs: int
    n_free: int
    backend: str
    relative_residual: float
    reaction_balance: float
    seconds: float


def _solve_reduced(K, force, free, free_index, dirichlet):
    """Solve ``K_ff u_f = f_f`` with SuperLU, falling back to the library CG."""
    indices = K.indices()
    values = K.values()
    free_mask = torch.zeros(force.numel(), dtype=torch.bool)
    free_mask[free] = True
    keep = free_mask[indices[0]] & free_mask[indices[1]]
    reduced = torch.sparse_coo_tensor(
        torch.stack((free_index[indices[0][keep]], free_index[indices[1][keep]])),
        values[keep], (len(free), len(free))).coalesce()
    if scipy_sparse_status().available:
        factor = factorize_sparse(reduced, method="splu")
        solution = factor.solve(force[free])
        residual = float(factor.last_relative_residual or 0.0)
        backend = "superlu(splu)"
    else:  # pragma: no cover - exercised only on a torch-only installation
        solved = solve_sparse_static(K, force, dirichlet=dirichlet, rtol=1e-10)
        solution = solved.displacement[free]
        residual = float(solved.iterative.relative_residual)
        backend = "cg(tensorfem)"
    return solution, backend, residual


def halfspace_level(label: str, lateral: float, depth: float, n_fine: int, n_grow: int,
                    nz_layers: int, cfg: dict = HALFSPACE) -> tuple[dict, HalfSpaceSolution]:
    """One truncated quarter model of the loaded half-space, graded against Boussinesq."""
    started = time.perf_counter()
    a = cfg["half_width"]
    h0 = a / n_fine
    xs = graded_axis(h0, n_fine, None, n_grow, lateral * a)
    ys = xs.clone()
    zs = graded_axis(h0, 0, None, nz_layers, depth * a)
    nodes, cells, (nx, ny, nz) = graded_box_mesh(xs, ys, zs)
    n_elements = len(cells)
    modulus = elasticity_matrix_3d(nodes.new_tensor(cfg["young"]).expand(n_elements),
                                   nodes.new_tensor(cfg["poisson"]).expand(n_elements))
    ke, _ = hex8_stiffness(nodes[cells], modulus)
    element_dofs = torch.stack(tuple(3 * cells + i for i in range(3)), dim=2).reshape(n_elements, 24).long()
    ndof = 3 * len(nodes)
    K = assemble_coo(ke, element_dofs, ndof, csr=False).coalesce()

    def node(i: int, j: int, k: int) -> int:
        return (i * (ny + 1) + j) * (nz + 1) + k

    force = torch.zeros(ndof, dtype=DTYPE)
    for i in range(n_fine):
        for j in range(n_fine):
            share = cfg["pressure"] * float(xs[i + 1] - xs[i]) * float(ys[j + 1] - ys[j]) / 4.0
            for ci, cj in ((i, j), (i + 1, j), (i + 1, j + 1), (i, j + 1)):
                force[3 * node(ci, cj, 0) + 2] += share
    applied = cfg["pressure"] * a * a

    fixed: dict[int, float] = {}
    for j in range(ny + 1):
        for k in range(nz + 1):
            fixed[3 * node(0, j, k)] = 0.0          # symmetry plane x = 0
            fixed[3 * node(nx, j, k)] = 0.0         # roller on x = L
    for i in range(nx + 1):
        for k in range(nz + 1):
            fixed[3 * node(i, 0, k) + 1] = 0.0      # symmetry plane y = 0
            fixed[3 * node(i, ny, k) + 1] = 0.0     # roller on y = L
    for i in range(nx + 1):
        for j in range(ny + 1):
            fixed[3 * node(i, j, nz) + 2] = 0.0     # bottom fixed in u_z
    fixed_dofs = torch.tensor(sorted(fixed), dtype=torch.long)
    mask = torch.ones(ndof, dtype=torch.bool)
    mask[fixed_dofs] = False
    free = torch.arange(ndof)[mask]
    free_index = torch.full((ndof,), -1, dtype=torch.long)
    free_index[free] = torch.arange(len(free))

    solution, backend, residual = _solve_reduced(K, force, free, free_index, fixed)
    displacement = torch.zeros(ndof, dtype=DTYPE)
    displacement[free] = solution

    centre = node(0, 0, 0)
    corner = node(n_fine, n_fine, 0)
    w_centre = float(displacement[3 * centre + 2])
    w_corner = float(displacement[3 * corner + 2])
    exact_centre = settlement(cfg["pressure"], cfg["young"], cfg["poisson"], 2 * a, 2 * a, a, a)
    exact_corner = settlement(cfg["pressure"], cfg["young"], cfg["poisson"], 2 * a, 2 * a, 2 * a, 2 * a)
    bottom = torch.tensor([3 * node(i, j, nz) + 2 for i in range(nx + 1) for j in range(ny + 1)])
    reaction = -float((K @ displacement - force)[bottom].sum())
    balance = abs(reaction - applied) / applied

    row = {
        "level": label,
        "lateral_extent_in_patch_widths": lateral,
        "depth_extent_in_patch_widths": depth,
        "n_fine": n_fine,
        "n_grow": n_grow,
        "nz_layers": nz_layers,
        "elements": n_elements,
        "nodes": int(len(nodes)),
        "dofs": int(ndof),
        "free_dofs": int(len(free)),
        "first_cell_size_over_a": h0 / a,
        "w_centre": w_centre,
        "w_centre_exact": exact_centre,
        "relative_error": (w_centre - exact_centre) / exact_centre,
        "w_corner": w_corner,
        "w_corner_exact": exact_corner,
        "corner_relative_error": (w_corner - exact_corner) / exact_corner,
        "reaction_balance_rel": balance,
        "solver": backend,
        "relative_residual": residual,
        "seconds": time.perf_counter() - started,
    }
    return row, HalfSpaceSolution(displacement, nodes, (nx, ny, nz), n_elements, ndof,
                                  len(free), backend, residual, balance, row["seconds"])


def halfspace_profile(solved: HalfSpaceSolution, cfg: dict = HALFSPACE) -> dict:
    """Surface settlement along the patch axis and diagonal, FE vs Boussinesq."""
    a = cfg["half_width"]
    nodes, (nx, ny, nz) = solved.nodes, solved.axes

    def node(i: int, j: int) -> int:
        return (i * (ny + 1) + j) * (nz + 1)

    axis_x, axis_w, axis_exact = [], [], []
    diag_r, diag_w, diag_exact = [], [], []
    for i in range(nx + 1):
        x = float(nodes[node(i, 0), 0])
        axis_x.append(x / a)
        axis_w.append(float(solved.displacement[3 * node(i, 0) + 2]))
        axis_exact.append(settlement(cfg["pressure"], cfg["young"], cfg["poisson"],
                                     2 * a, 2 * a, x + a, a))
        if i <= ny:
            y = float(nodes[node(i, i), 1])
            diag_r.append(math.hypot(x, y) / a)
            diag_w.append(float(solved.displacement[3 * node(i, i) + 2]))
            diag_exact.append(settlement(cfg["pressure"], cfg["young"], cfg["poisson"],
                                         2 * a, 2 * a, x + a, y + a))
    return {"axis_x_over_a": axis_x, "axis_w": axis_w, "axis_w_exact": axis_exact,
            "diag_r_over_a": diag_r, "diag_w": diag_w, "diag_w_exact": diag_exact}


def halfspace_solver_cross_check(row: dict, cfg: dict = HALFSPACE) -> dict:
    """Re-solve the same level with the library unpreconditioned-CG path."""
    started = time.perf_counter()
    library = solve_halfspace_patch(
        young=cfg["young"], poisson=cfg["poisson"], pressure=cfg["pressure"],
        half_width=cfg["half_width"], lateral=row["lateral_extent_in_patch_widths"],
        depth=row["depth_extent_in_patch_widths"], n_fine=row["n_fine"],
        n_grow=row["n_grow"], nz_layers=row["nz_layers"], rtol=1e-10)
    return {
        "level": row["level"],
        "library_backend": "cg(tensorfem solve_sparse_static)",
        "library_w_centre": library.w_center,
        "direct_w_centre": row["w_centre"],
        "relative_difference": abs(library.w_center - row["w_centre"]) / abs(row["w_centre"]),
        "library_seconds": time.perf_counter() - started,
    }


# --------------------------------------------------------------------------- #
# refinement ordering, figures, documentation block
# --------------------------------------------------------------------------- #
def refinement_summary(rows: list[dict], error_key: str = "relative_error") -> dict:
    """Monotone refinement check plus observed contraction factors for one ladder."""
    errors = [abs(row[error_key]) for row in rows]
    non_increasing = all(
        later <= earlier * (1.0 + 1e-9) for earlier, later in zip(errors, errors[1:]))
    ratios = [earlier / later for earlier, later in zip(errors, errors[1:]) if later > 0.0]
    return {
        "levels": len(rows),
        "absolute_errors": errors,
        "non_increasing": non_increasing,
        "contraction_factors": ratios,
        "finest_absolute_error": errors[-1] if errors else None,
        "meets_min_levels": len(rows) >= TOLERANCES["min_refinement_levels"],
    }


def _fig_beam(beam: dict) -> None:
    fig, ax = plt.subplots(figsize=(6.4, 4.4))
    frame, solid = beam["frame_levels"], beam["solid_levels"]
    ax.semilogy([row["n_elements"] for row in frame],
                [max(abs(row["relative_error"]), 1e-16) for row in frame],
                "o-", label="frame2d cubic Hermite (Euler-Bernoulli)")
    ax.semilogy([row["axial_elements"] for row in solid],
                [abs(row["relative_error"]) for row in solid],
                "s-", label="HEX20 3-D solid")
    ax.axhline(TOLERANCES["beam_tip_rel_error_max"], color="k", ls="--", lw=1,
               label="3% acceptance")
    ax.set_xlabel("elements along the member")
    ax.set_ylabel("|relative error| of the tip deflection")
    ax.set_title(f"Cantilever L/h = {beam['analytic']['slenderness']:.0f}: tip deflection")
    ax.grid(True, which="both", alpha=0.3)
    ax.legend()
    fig.tight_layout()
    fig.savefig(ASSETS / "beam_convergence.png", dpi=140)
    plt.close(fig)


def _fig_plate(plate: dict, field) -> None:
    nodes, w = field
    n = int(round(math.sqrt(len(nodes)))) - 1
    x = nodes[:, 0].reshape(n + 1, n + 1).numpy()
    y = nodes[:, 1].reshape(n + 1, n + 1).numpy()
    grid = w.reshape(n + 1, n + 1).numpy()
    fig, axes = plt.subplots(1, 2, figsize=(11.0, 4.3))
    contour = axes[0].contourf(x, y, grid, levels=20, cmap="viridis")
    fig.colorbar(contour, ax=axes[0], label="w [m]")
    axes[0].set_title(f"SS plate deflection field, n = {n} (uniform pressure)")
    axes[0].set_xlabel("x [m]")
    axes[0].set_ylabel("y [m]")
    axes[0].set_aspect("equal")
    rows = plate["levels"]
    axes[1].semilogy([row["elements_per_side"] for row in rows],
                     [abs(row["relative_error"]) for row in rows], "o-",
                     label="Q4 Mindlin (SRI)")
    axes[1].axhline(TOLERANCES["plate_center_rel_error_max"], color="k", ls="--", lw=1,
                    label="5% acceptance")
    axes[1].set_xlabel("elements per side")
    axes[1].set_ylabel("|relative error| of the centre deflection")
    axes[1].set_title("Centre deflection vs Navier series")
    axes[1].grid(True, which="both", alpha=0.3)
    axes[1].legend()
    fig.tight_layout()
    fig.savefig(ASSETS / "plate_field_convergence.png", dpi=140)
    plt.close(fig)


