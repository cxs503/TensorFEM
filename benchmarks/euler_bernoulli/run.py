"""Analytic benchmarks for the three classical structural models of TensorFEM.

Three independent checks, each graded against a *closed-form* reference and each
run over a refinement ladder so that the discretisation error, not just a single
number, is on the record:

1. **Euler-Bernoulli cantilever** (slenderness ``L/h = 100``, tip point load).
   Two discretisations of the same member are graded against
   ``delta = P L^3 / (3 E I)``:

   * ``frame2d`` cubic-Hermite beam elements -- nodally exact for this load, so
     the ladder measures the algebra (round-off), not the physics;
   * a **3-D HEX20 solid** model of the same bar -- a genuine h-ladder, because
     the solid model must *converge* to the beam theory the element is allowed
     to assume.  Levels: 10 and 20 quadratic elements along the axis plus a
     cross-section refinement, so the reported error is a discretisation error
     and not a re-statement of the beam formula.

2. **Thin square plate under uniform pressure**, hard simple supports, Q4
   Mindlin elements with selective reduced integration (``a/t = 100``, so the
   Kirchhoff limit is the right yardstick).  Reference: the closed-form Navier
   double series evaluated in this script (399 x 399 odd terms), with the
   textbook coefficient ``0.00406`` reported as a second, independent anchor.
   Levels: ``n = 8, 16, 24`` elements per side.

3. **Boussinesq half-space settlement** (3-D elasticity, unbounded domain).
   A uniform pressure on a ``2a x 2a`` patch on an isotropic half-space.  The
   quarter model is the graded HEX8 box of :mod:`tensorfem.elastic_halfspace`
   (symmetry planes, rollers on the outer faces, bottom fixed in ``u_z``); the
   reference is the Boussinesq/Love closed form
   ``w = (p (1-nu^2)/(pi E)) * int_A dA/|x-xi|``.  Because the kernel decays like
   ``1/r`` the *truncation radius* is a physical error source that no residual or
   reaction check can see, so the ladder refines the mesh at a fixed box
   (levels 1-2) and then grows the box (levels 3-4).  The linear system is solved
   with the SuperLU adapter of :mod:`tensorfem.sparse_direct`; the coarsest level
   is re-solved with the library unpreconditioned-CG path as an equivalence check.

Outputs (relative to the repository root)
-----------------------------------------
* ``benchmarks/euler_bernoulli/results.json`` -- every number, machine graded
* ``docs/assets/fem_verify/*.png``            -- convergence and field figures
* ``docs/FEM_VERIFY.md``                      -- convergence tables injected
  between the generated-block markers (the prose is not touched)

Usage::

    OMP_NUM_THREADS=8 PYTHONPATH=src python benchmarks/euler_bernoulli/run.py
    OMP_NUM_THREADS=8 PYTHONPATH=src python benchmarks/euler_bernoulli/run.py --skip-halfspace
"""

