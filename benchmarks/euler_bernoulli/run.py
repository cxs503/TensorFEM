def run(skip_halfspace: bool = False, halfspace_levels=HALFSPACE_LEVELS,
        cross_check: bool = True) -> dict:
    ASSETS.mkdir(parents=True, exist_ok=True)
    results: dict = {
        "benchmark": "euler_bernoulli_cantilever + thin_plate + boussinesq_halfspace",
        "generated_by": "benchmarks/euler_bernoulli/run.py",
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "environment": {
            "python": platform.python_version(),
            "torch": torch.__version__,
            "machine": platform.machine(),
            "dtype": str(DTYPE),
        },
        "tolerances": dict(TOLERANCES),
    }

    print("[1/3] Euler-Bernoulli cantilever (L/h = 100)", flush=True)
    analytic = beam_analytic()
    frame = beam_frame_levels()
    solid = beam_solid_levels()
    beam_error = max(abs(frame[-1]["relative_error"]), abs(solid[-1]["relative_error"]))
    beam_refine = refinement_summary(solid)
    beam_refine["frame_ladder_absolute_errors"] = [abs(r["relative_error"]) for r in frame]
    results["beam"] = {
        "geometry": dict(BEAM),
        "analytic": analytic,
        "frame_levels": frame,
        "solid_levels": solid,
        "finest_relative_error": beam_error,
        "refinement": beam_refine,
        "passed": beam_error <= TOLERANCES["beam_tip_rel_error_max"]
                  and beam_refine["meets_min_levels"],
    }
    for row in frame:
        print(f"    frame  n={row['n_elements']:3d} tip={row['tip_deflection']:.6e} "
              f"err={_pct(row['relative_error'])}", flush=True)
    for row in solid:
        print(f"    hex20  axial={row['axial_elements']:3d} cross={row['cross_elements']} "
              f"tip={row['tip_deflection']:.6e} err={_pct(row['relative_error'])}", flush=True)

    print("[2/3] Thin SS plate under uniform pressure (a/t = 100)", flush=True)
    plate_rows, plate_extra = plate_levels()
    plate_refine = refinement_summary(plate_rows)
    plate_error = abs(plate_rows[-1]["relative_error"])
    results["plate"] = {
        "geometry": dict(PLATE),
        "reference": dict(plate_extra["reference"]),
        "levels": plate_rows,
        "shear_cross_check": plate_extra["shear_cross_check"],
        "finest_relative_error": plate_error,
        "refinement": plate_refine,
        "passed": plate_error <= TOLERANCES["plate_center_rel_error_max"]
                  and plate_refine["meets_min_levels"],
    }
    for row in plate_rows:
        print(f"    plate n={row['elements_per_side']:2d} w_c={row['centre_deflection']:.6e} "
              f"err={_pct(row['relative_error'])}", flush=True)

    if skip_halfspace:
        results["halfspace"] = {
            "skipped": True, "passed": None, "levels": [],
            "finest_relative_error": None,
            "refinement": {"levels": 0, "meets_min_levels": False,
                           "non_increasing": False, "absolute_errors": [],
                           "contraction_factors": [], "finest_absolute_error": None},
        }
    else:
        print("[3/3] Boussinesq half-space settlement (3-D elasticity)", flush=True)
        rows, finest = [], None
        for level in halfspace_levels:
            row, solved = halfspace_level(*level)
            rows.append(row)
            finest = solved
            print(f"    {row['level']:>14s} el={row['elements']:6d} "
                  f"free={row['free_dofs']:6d} w_c={row['w_centre']:.6e} "
                  f"err={_pct(row['relative_error'])} "
                  f"bal={row['reaction_balance_rel']:.1e} t={row['seconds']:.0f}s",
                  flush=True)
        half_refine = refinement_summary(rows)
        half_error = abs(rows[-1]["relative_error"])
        results["halfspace"] = {
            "geometry": dict(HALFSPACE),
            "reference": {"formula": "Boussinesq/Love: w=(p(1-nu^2)/(pi E)) int_A dA/|x-xi|"},
            "levels": rows,
            "profile": halfspace_profile(finest),
            "solver_cross_check": halfspace_solver_cross_check(rows[0]) if cross_check else None,
            "finest_relative_error": half_error,
            "refinement": half_refine,
            "passed": half_error <= TOLERANCES["halfspace_center_rel_error_max"]
                      and half_refine["meets_min_levels"],
        }

    verdict = {
        "beam_tip_le_3pct": bool(results["beam"]["passed"]),
        "plate_centre_le_5pct": bool(results["plate"]["passed"]),
        "halfspace_centre_le_5pct": bool(results["halfspace"].get("passed")),
        "convergence": bool(results["beam"]["refinement"]["meets_min_levels"]
                            and results["plate"]["refinement"]["meets_min_levels"]
                            and results["halfspace"]["refinement"]["meets_min_levels"]),
    }
    verdict["all_passed"] = all(verdict.values())
    results["verdict"] = verdict

    _fig_beam(results["beam"])
    _fig_plate(results["plate"], plate_extra["field"])
    if not skip_halfspace:
        _fig_halfspace(results["halfspace"])

    injected = inject_doc(results)
    results["artifacts"] = {
        "results_json": str(RESULTS.relative_to(ROOT)),
        "doc": str(DOC.relative_to(ROOT)),
        "doc_tables_injected": injected,
        "figures": sorted(p.name for p in ASSETS.glob("*.png")),
    }
    RESULTS.write_text(json.dumps(results, indent=2) + "\n", encoding="utf-8")
    print(f"\nwrote {RESULTS.relative_to(ROOT)}; doc tables injected: {injected}")
    print(json.dumps(verdict, indent=2))
    return results


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--skip-halfspace", action="store_true",
                        help="run only the beam and plate ladders (fast)")
    parser.add_argument("--no-cross-check", action="store_true",
                        help="skip the CG re-solve of the coarsest half-space level")
    args = parser.parse_args()
    results = run(skip_halfspace=args.skip_halfspace, cross_check=not args.no_cross_check)
    return 0 if results["verdict"]["all_passed"] or args.skip_halfspace else 1


