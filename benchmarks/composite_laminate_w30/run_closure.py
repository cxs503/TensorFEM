#!/usr/bin/env python
"""W30 composite-laminate verification: anchor closure ledger.

(1) **anchor closure** -- the anchor values generated by :mod:`symbolic_anchor`
    (50-digit ``mpmath``, transformation-matrix algebra, exact thickness
    integration) against two independent code paths: :mod:`clt_independent`
    (double precision, textbook power formulas) and TensorFEM's own
    ``Laminate.abd()`` (rotated 3-D stiffness + condensation).  Criterion: the
    relative residual of every ``A``, ``B``, ``D``, ``As`` entry <= 0.1 % of the
    block scale.

(2) **failure-index comparison** -- Tsai-Wu (``F12* = -1/2``), Tsai-Hill and
    maximum stress evaluated ply by ply on the same strain state, anchor vs the
    two code paths.  Criterion: per-point relative deviation < 15 %.

(3) **solver table** -- layups x in-plane load cases for the membrane response,
    plus a transverse-load table that separates the three error sources the
    mission asks about: element discretisation (Q4 Mindlin FE vs the analytic
    Navier amplitude), shear correction (FSDT ``k = 5/6`` vs CLT) and the
    coupling terms (``B != 0``, ``A16 != 0`` layups).

Nothing is transcribed: every number is read from the anchor file, recomputed in
this process, or read out of a TensorFEM call, and the artifact records the
sha256 of every script and of the anchor file plus the git commit.

Usage::

    PYTHONPATH=src python benchmarks/composite_laminate_w30/run_closure.py
    PYTHONPATH=src python benchmarks/composite_laminate_w30/run_closure.py --selftest
"""
