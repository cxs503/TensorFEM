# -- pre-declared thresholds, fixed before any result was inspected ---------
CRIT = {
    "abd_rel_pct_max": 0.1,        # criterion (1)
    "index_rel_pct_max": 15.0,     # criterion (2)
    "calibration_abs_max": 1e-12,  # criterion identities
    "min_layups": 2,
    "min_load_cases": 3,
}

CRITERIA = ("tsai_wu", "tsai_hill", "max_stress")
PLY_T = float(sa.PLY_THICKNESS)
BENDING = {"B1_thin_a_over_t_100": 100.0, "B2_thick_a_over_t_10": 10.0}
BENDING_Q0 = 1.0e5
#: cross-ply for the closed-form bending references: [0/90/0/90]s has
#: ``D16 = D26 = 0`` (special orthotropic), which the analytic Navier amplitudes
#: of TensorFEM require.  The angle-ply [0/90/+-45]s is *balanced* (A16 = A26 = 0)
#: but not special orthotropic -- its bending-twisting coupling is quantified in
#: ``coupling_diagnostics`` instead of being hidden.
BEND_ANGLES = ci.symmetric([0.0, 90.0, 0.0, 90.0])


# ── helpers ────────────────────────────────────────────────────────────────
def sha256_file(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def git_commit() -> str:
    try:
        return subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=REPO,
                                       text=True).strip()
    except Exception:
        return "unavailable"


def ply_props() -> "ci.PlyProperties":
    m = sa.MATERIAL
    return ci.PlyProperties(
        E1=float(m["E1"]), E2=float(m["E2"]), nu12=float(m["nu12"]),
        G12=float(m["G12"]), G13=float(m["G13"]), G23=float(m["G23"]),
        Xt=float(m["Xt"]), Xc=float(m["Xc"]), Yt=float(m["Yt"]),
        Yc=float(m["Yc"]), S=float(m["S"]), name=m["name"])


def mat_rel_dev(a, b, scale=None) -> float:
    """max |a_ij - b_ij| / scale.

    ``scale`` is the *layup-level* magnitude of the anchor (max over A, B and D).
    A per-block denominator is unusable: for a symmetric laminate the whole ``B``
    block, and for some layups single ``D16``/``D26`` entries, are exact zeros that
    survive only as round-off in a 60-digit computation, so a per-block
    denominator would report 100 % for a 1e-45 residue.
    """
    a = np.asarray(a, dtype=float)
    b = np.asarray(b, dtype=float)
    ref = scale if scale else max(np.max(np.abs(b)), np.max(np.abs(a)), 1e-300)
    return float(np.max(np.abs(a - b)) / ref)


def tf_q(theta_deg: float) -> np.ndarray:
    """TensorFEM plane-stress reduced stiffness of one rotated ply."""
    C = ply_stiffness_3d(IM7_8552_MATERIAL, theta_deg)
    ip, op = [0, 1, 5], [2, 3, 4]
    return C[np.ix_(ip, ip)] - C[np.ix_(ip, op)] @ np.linalg.solve(
        C[np.ix_(op, op)], C[np.ix_(op, ip)])


def tf_ply_stress(theta_deg: float, eps0, kappa, z: float) -> np.ndarray:
    """TensorFEM stiffness -> global stress -> material axes."""
    sig = tf_q(theta_deg) @ (np.asarray(eps0) + z * np.asarray(kappa))
    t = np.radians(theta_deg)
    m, n = np.cos(t), np.sin(t)
    return np.array([m * m * sig[0] + n * n * sig[1] + 2 * m * n * sig[2],
                     n * n * sig[0] + m * m * sig[1] - 2 * m * n * sig[2],
                     -m * n * sig[0] + m * n * sig[1] + (m * m - n * n) * sig[2]])


def index_of(ply, s, criterion: str) -> float:
    return ci.CRITERIA[criterion](ply, s[0], s[1], s[2])


# ── criterion 1: ABD closure ───────────────────────────────────────────────
def abd_closure(anchor: dict, ply) -> dict:
    rows, devs_i, devs_t = [], [], []
    for key, data in anchor["layups"].items():
        angles = data["angles_deg"]
        thicknesses = [PLY_T] * len(angles)
        A_i, B_i, D_i, As_i = ci.abd(ply, angles, thicknesses, shear_correction=1.0)
        lam = Laminate(angles_deg=angles, ply_thickness=PLY_T,
                       material=IM7_8552_MATERIAL)
        A_t, B_t, D_t, As_t = lam.abd()
        block_scale = max(float(np.max(np.abs(np.asarray(data[blk], dtype=float))))
                          for blk in ("A", "B", "D")) or 1.0
        for name, ind, tf in (("A", A_i, A_t), ("B", B_i, B_t), ("D", D_i, D_t)):
            anc = np.asarray(data[name], dtype=float)
            d_i = mat_rel_dev(ind, anc, block_scale)
            d_t = mat_rel_dev(tf, anc, block_scale)
            devs_i.append(d_i)
            devs_t.append(d_t)
            rows.append({
                "layup": key, "block": name,
                "anchor": anc.tolist(), "independent": np.asarray(ind).tolist(),
                "tensorfem": np.asarray(tf).tolist(),
                "rel_dev_independent_pct": 100.0 * d_i,
                "rel_dev_tensorfem_pct": 100.0 * d_t,
                "abs_dev_max_tensorfem": float(np.max(np.abs(np.asarray(tf) - anc))),
                "matrix_scale": block_scale,
                "threshold_pct": CRIT["abd_rel_pct_max"],
                "verdict": "PASS" if 100.0 * max(d_i, d_t) <= CRIT["abd_rel_pct_max"]
                           else "FAIL",
            })
        As_anc = np.asarray(data["As_uncorrected"], dtype=float)
        d_i = mat_rel_dev(As_i, As_anc)
        d_t = mat_rel_dev(As_t, As_anc)
        devs_i.append(d_i)
        devs_t.append(d_t)
        rows.append({
            "layup": key, "block": "As_uncorrected",
            "anchor": As_anc.tolist(), "independent": np.asarray(As_i).tolist(),
            "tensorfem": np.asarray(As_t).tolist(),
            "rel_dev_independent_pct": 100.0 * d_i,
            "rel_dev_tensorfem_pct": 100.0 * d_t,
            "abs_dev_max_tensorfem": float(np.max(np.abs(np.asarray(As_t) - As_anc))),
            "matrix_scale": float(np.max(np.abs(As_anc))),
            "threshold_pct": CRIT["abd_rel_pct_max"],
            "verdict": "PASS" if 100.0 * max(d_i, d_t) <= CRIT["abd_rel_pct_max"]
                       else "FAIL",
            "note": "uncorrected (k = 1) shear block; FSDT applies 5/6 later",
        })
    wi, wt = max(devs_i), max(devs_t)
    return {
        "threshold_pct": CRIT["abd_rel_pct_max"],
        "normalisation": "max|deviation| / max over the layup's A, B, D entries "
                         "(a per-block denominator is meaningless where the block "
                         "is an exact zero, e.g. B of a symmetric layup)",
        "rows": rows,
        "worst_rel_dev_independent_pct": 100.0 * wi,
        "worst_rel_dev_tensorfem_pct": 100.0 * wt,
        "verdict": "PASS" if 100.0 * max(wi, wt) <= CRIT["abd_rel_pct_max"] else "FAIL",
    }


# ── criterion 2: failure-index comparison ─────────────────────────────────
def index_closure(anchor: dict, ply) -> dict:
    rows = []
    for key, data in anchor["layups"].items():
        angles = data["angles_deg"]
        thicknesses = [PLY_T] * len(angles)
        lam = Laminate(angles_deg=angles, ply_thickness=PLY_T,
                       material=IM7_8552_MATERIAL)
        A_t, B_t, D_t, _ = lam.abd()
        K_t = np.block([[A_t, B_t], [B_t, D_t]])
        for lc, anc_lc in data["load_cases"].items():
            N = np.asarray(anc_lc["N_N_per_m"], dtype=float)
            eps_i, kap_i = ci.clt_response(ply, angles, thicknesses, N)
            sol = np.linalg.solve(K_t, np.concatenate([N, np.zeros(3)]))
            eps_t, kap_t = sol[:3], sol[3:]
            for a_ply in anc_lc["plies"]:
                th = a_ply["angle_deg"]
                s_i = ci.ply_stress(ply, th, eps_i, kap_i, 0.0)
                s_t = tf_ply_stress(th, eps_t, kap_t, 0.0)
                for crit in CRITERIA:
                    a_val = a_ply["index"][crit]
                    i_val = index_of(ply, s_i, crit)
                    t_val = index_of(ply, s_t, crit)
                    d_i = abs(i_val - a_val) / a_val * 100.0
                    d_t = abs(t_val - a_val) / a_val * 100.0
                    rows.append({
                        "layup": key, "load_case": lc, "ply": a_ply["ply"],
                        "angle_deg": th, "criterion": crit,
                        "anchor_index": a_val, "independent_index": i_val,
                        "tensorfem_index": t_val,
                        "sigma_anchor_Pa": [a_ply["sigma1_Pa"], a_ply["sigma2_Pa"],
                                            a_ply["tau12_Pa"]],
                        "sigma_independent_Pa": s_i.tolist(),
                        "sigma_tensorfem_Pa": s_t.tolist(),
                        "rel_dev_independent_pct": d_i,
                        "rel_dev_tensorfem_pct": d_t,
                        "threshold_pct": CRIT["index_rel_pct_max"],
                        "verdict": "PASS" if max(d_i, d_t) < CRIT["index_rel_pct_max"]
                                   else "FAIL",
                    })
    devs = [max(r["rel_dev_independent_pct"], r["rel_dev_tensorfem_pct"]) for r in rows]
    fails = [r for r in rows if r["verdict"] == "FAIL"]
    return {
        "threshold_pct": CRIT["index_rel_pct_max"],
        "n_points": len(rows), "n_fail": len(fails),
        "worst_rel_dev_pct": max(devs), "median_rel_dev_pct": float(np.median(devs)),
        "rows": rows,
        "failures": [{"layup": r["layup"], "load_case": r["load_case"], "ply": r["ply"],
                      "criterion": r["criterion"], "dev_pct":
                      max(r["rel_dev_independent_pct"], r["rel_dev_tensorfem_pct"])}
                     for r in fails],
        "verdict": "PASS" if not fails else "FAIL",
    }


# ── criterion identities ───────────────────────────────────────────────────
def calibration(anchor: dict, ply) -> dict:
    rows, worst = [], 0.0
    m = sa.MATERIAL
    for entry in anchor["calibration"]:
        state = entry["state"]
        s1 = s2 = t12 = 0.0
        if state.startswith("sigma1"):
            s1 = float(m["Xt"]) if state.endswith("+Xt") else -float(m["Xc"])
        elif state.startswith("sigma2"):
            s2 = float(m["Yt"]) if state.endswith("+Yt") else -float(m["Yc"])
        else:
            t12 = float(m["S"])
        got = index_of(ply, np.array([s1, s2, t12]), entry["criterion"])
        err = abs(got - 1.0)
        worst = max(worst, err)
        rows.append({"id": entry["id"], "criterion": entry["criterion"], "state": state,
                     "anchor_index": entry["index"], "recomputed_index": got,
                     "abs_error": err})
    return {"rows": rows, "worst_abs_error": worst,
            "threshold": CRIT["calibration_abs_max"],
            "verdict": "PASS" if worst <= CRIT["calibration_abs_max"] else "FAIL"}


# ── solver table: bending ─────────────────────────────────────────────────
def bending_table(ply) -> dict:
    """Transverse load on the cross-ply [0/90/0/90]s: CLT vs FSDT vs Q4 FE."""
    out = {}
    angles = BEND_ANGLES
    lam = Laminate(angles_deg=angles, ply_thickness=PLY_T, material=IM7_8552_MATERIAL)
    t_total = lam.thickness
    for case, ratio in BENDING.items():
        a = b = ratio * t_total
        clt = navier_clt(lam, a, b, q0=BENDING_Q0)
        fsdt = navier_fsdt(lam, a, b, q0=BENDING_Q0)
        levels = []
        for n in (8, 16, 24):
            fem = plate_fem(lam, a, q0=BENDING_Q0, b=b, n=n)
            levels.append({"n": n, "w_center": fem["w_center"],
                           "n_elements": fem["n_elements"], "residual": fem["residual"],
                           "rel_dev_vs_fsdt_pct": 100.0 * (fem["w_center"]
                                                           - fsdt.center_deflection)
                                                  / fsdt.center_deflection})
        scale = levels[-1]["w_center"] / fsdt.center_deflection
        al, be = np.pi / a, np.pi / b
        kappa = {
            "CLT": np.array([clt.X * al, clt.Y * be, clt.X * be + clt.Y * al]),
            "FSDT": np.array([fsdt.X * al, fsdt.Y * be, fsdt.X * be + fsdt.Y * al]),
        }
        kappa["FE_scaled"] = scale * kappa["FSDT"]
        z_bot = -0.5 * t_total
        ply_rows = []
        for k, th in enumerate(angles):
            sig = {name: tf_ply_stress(th, np.zeros(3), kap, z_bot)
                   for name, kap in kappa.items()}
            ply_rows.append({
                "ply": k, "angle_deg": th,
                "sigma_bottom_Pa": {nm: sig[nm].tolist() for nm in sig},
                "index": {nm: {c: index_of(ply, sig[nm], c) for c in CRITERIA}
                          for nm in sig},
            })
        comp = {}
        for c in CRITERIA:
            hot = max(range(len(ply_rows)),
                      key=lambda i: ply_rows[i]["index"]["CLT"][c])
            i0 = ply_rows[hot]["index"]
            dev_shear = 100.0 * (i0["FSDT"][c] - i0["CLT"][c]) / i0["CLT"][c]
            comp[c] = {
                "hot_ply": hot, "angle_deg": angles[hot],
                "CLT": i0["CLT"][c], "FSDT": i0["FSDT"][c], "FE_scaled": i0["FE_scaled"][c],
                "dev_FSDT_vs_CLT_pct": dev_shear,
                "dev_FE_vs_FSDT_pct": 100.0 * (i0["FE_scaled"][c] - i0["FSDT"][c])
                                      / i0["FSDT"][c],
                "verdict_vs_15pct": "PASS" if abs(dev_shear) < CRIT["index_rel_pct_max"]
                                    else "FAIL",
            }
        out[case] = {
            "a_over_t": ratio, "a_m": a, "b_m": b, "q0_Pa": BENDING_Q0,
            "thickness_m": t_total,
            "w_center_CLT_m": clt.center_deflection,
            "w_center_FSDT_m": fsdt.center_deflection,
            "dev_FSDT_vs_CLT_pct": 100.0 * (fsdt.center_deflection
                                            - clt.center_deflection)
                                   / clt.center_deflection,
            "fe_levels": levels,
            "fe_finest_rel_dev_vs_FSDT_pct": levels[-1]["rel_dev_vs_fsdt_pct"],
            "kappa_amplitudes_1_per_m": {k: v.tolist() for k, v in kappa.items()},
            "ply_rows": ply_rows,
            "worst_ply_by_criterion": comp,
        }
    return out


def coupling_diagnostics(anchor: dict) -> dict:
    """Magnitude of the coupling blocks that CLT-uncoupled references cannot carry."""
    out = {}
    for key, data in anchor["layups"].items():
        A = np.asarray(data["A"], dtype=float)
        B = np.asarray(data["B"], dtype=float)
        D = np.asarray(data["D"], dtype=float)
        a_scale = max(abs(A[0, 0]), abs(A[1, 1]), abs(A[2, 2])) or 1.0
        d_scale = max(abs(D[0, 0]), abs(D[1, 1]), abs(D[2, 2])) or 1.0
        t_total = len(data["angles_deg"]) * PLY_T
        b_scale = a_scale * t_total          # B and D differ in dimension by one length
        out[key] = {
            "label": data["label"],
            "A16_over_A11": float(abs(A[0, 2]) / a_scale),
            "A26_over_A22": float(abs(A[1, 2]) / a_scale),
            "B_max_over_A_scale_x_t": float(np.max(np.abs(B)) / b_scale),
            "B_is_zero": bool(np.max(np.abs(B)) / b_scale < 1e-12),
            "thickness_m": t_total,
            "D16_over_D11": float(abs(D[0, 2]) / d_scale),
            "D26_over_D22": float(abs(D[1, 2]) / d_scale),
            "special_orthotropic": bool(abs(D[0, 2]) / d_scale < 1e-9
                                        and abs(D[1, 2]) / d_scale < 1e-9),
        }
    return out


# ── root-cause attribution ────────────────────────────────────────────────
def root_causes(index_tab: dict, bend: dict, cpl: dict) -> list:
    out = []
    for key in ("L3_coupled_B", "L4_coupled_A16"):
        sub = [r for r in index_tab["rows"] if r["layup"] == key]
        if not sub:
            continue
        devs = [max(r["rel_dev_independent_pct"], r["rel_dev_tensorfem_pct"])
                for r in sub]
        out.append({
            "factor": "coupling_terms",
            "layup": key,
            "evidence": f"max failure-index deviation {max(devs):.3e} % over "
                        f"{len(sub)} ply/criterion points with B != 0 / A16 != 0",
            "conclusion": "no measurable contribution: both paths invert the same "
                          "6x6 [A B; B D] system, so the coupling terms cancel "
                          "exactly in the residual (round-off level)",
        })
    l1 = cpl.get("L1_0_90_pm45_s", {})
    if l1:
        out.append({
            "factor": "coupling_terms (bending-twisting D16/D26) in the bending path",
            "layup": "L1_0_90_pm45_s",
            "evidence": f"D16/D11 = {l1['D16_over_D11']:.4f}, D26/D22 = "
                        f"{l1['D26_over_D22']:.4f} for [0/90/+-45]s; balanced in "
                        f"extension (A16/A11 = {l1['A16_over_A11']:.2e}) but NOT "
                        f"special orthotropic in bending",
            "conclusion": "the closed-form Navier amplitude used as the bending anchor "
                          "is only valid for D16 = D26 = 0, so the bending table runs on "
                          "the cross-ply [0/90/0/90]s; for the angle-ply layup the "
                          "coupling is real and only a Q4 FE or a full Navier "
                          "eigensolve can carry it",
        })
    for case, data in bend.items():
        c = data["worst_ply_by_criterion"]
        out.append({
            "factor": "shear_deformation (CLT vs FSDT with k = 5/6)",
            "case": case, "a_over_t": data["a_over_t"],
            "evidence": f"deflection deviates {data['dev_FSDT_vs_CLT_pct']:.3f} %; "
                        f"worst Tsai-Wu index (ply {c['tsai_wu']['hot_ply']}, "
                        f"{c['tsai_wu']['angle_deg']:g} deg) deviates "
                        f"{c['tsai_wu']['dev_FSDT_vs_CLT_pct']:.3f} %",
            "conclusion": "transverse shear inflates the ply bending stress; the "
                          "effect stays inside the 15 % band at a/t = 100 and must "
                          "be re-checked as a/t falls",
        })
        out.append({
            "factor": "element_type / discretisation (Q4 Mindlin FE vs analytic FSDT)",
            "case": case, "a_over_t": data["a_over_t"],
            "evidence": f"finest Q4 mesh n = {data['fe_levels'][-1]['n']}: centre "
                        f"deflection deviation "
                        f"{data['fe_finest_rel_dev_vs_FSDT_pct']:.4f} %",
            "conclusion": "Q4 Mindlin with MITC shear tying converges from above and "
                          "is already inside 0.1 % at n = 24; the ply index inherits "
                          "this error linearly",
        })
    return out


# ── figures ───────────────────────────────────────────────────────────────
def figures(artifact: dict) -> list:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

