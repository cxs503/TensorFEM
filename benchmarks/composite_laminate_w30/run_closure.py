# ── selftest ──────────────────────────────────────────────────────────────
def selftest(artifact: dict) -> int:
    ok = True

    def check(name, cond, detail=""):
        nonlocal ok
        print(f"[{'PASS' if cond else 'FAIL'}] {name} {detail}")
        ok = ok and bool(cond)

    ab = artifact["criterion_1_ABD_closure"]
    check("ABD closure <= 0.1 %", ab["verdict"] == "PASS",
          f"worst {max(ab['worst_rel_dev_independent_pct'], ab['worst_rel_dev_tensorfem_pct']):.2e} %")
    it = artifact["criterion_2_failure_index"]
    check("failure index < 15 %", it["verdict"] == "PASS",
          f"worst {it['worst_rel_dev_pct']:.2e} % over {it['n_points']} points")
    cal = artifact["calibration_identities"]
    check("criterion identities = 1", cal["verdict"] == "PASS",
          f"worst |err| {cal['worst_abs_error']:.2e}")
    cov = artifact["criterion_3_coverage"]
    check("coverage layups x load cases", cov["verdict"] == "PASS",
          f"{cov['n_layups']} x {cov['n_in_plane_load_cases']}")
    check("every index row has a verdict",
          all(r.get("verdict") in ("PASS", "FAIL") for r in it["rows"]))
    check("every ABD row carries anchor + both code paths",
          all(r.get("anchor") and r.get("independent") and r.get("tensorfem")
              for r in ab["rows"]))
    check("anchor file hashed", bool(artifact["provenance"]["anchor_values_sha256"]))
    bend = artifact["bending_table"]
    check("bending table has both slenderness cases", len(bend) == len(BENDING))
    return 0 if ok else 1


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--selftest", action="store_true")
    ap.add_argument("--no-figures", action="store_true")
    ap.add_argument("--out", default=str(ARTIFACT))
    args = ap.parse_args(argv)
    if not (HERE / "anchor_values.json").exists():
        print("anchor_values.json missing -- run symbolic_anchor.py first", file=sys.stderr)
        return 2
    artifact = build_artifact()
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    artifact["figures"] = [] if args.no_figures else figures(artifact)
    text = json.dumps(artifact, indent=1, sort_keys=True)
    Path(args.out).write_text(text)
    print(f"artifact written: {args.out}")
    print(f"  sha256 {hashlib.sha256(text.encode()).hexdigest()}")
    for v in artifact["verdicts"]:
        print(f"  [{v['verdict']}] {v['criterion']}: "
              f"{v.get('value_pct', v.get('value'))}")
    return selftest(artifact) if args.selftest else 0


