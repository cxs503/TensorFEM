#!/usr/bin/env python3
"""Render the device-debt overview figure from ``artifacts/fem_debt_census.json``.

The figure is a pure function of the census JSON (no wall clock, no random
sampling, sorted inputs) so it can be regenerated byte-for-byte alongside the
report it illustrates.

Usage::

    python tools/debt_census_figure.py                        # -> artifacts/figs/fem_debt_overview.png
    python tools/debt_census_figure.py --dpi 70 --out /tmp/small.png
"""
from __future__ import annotations

import argparse
import json
import pathlib

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

TOP_N = 12


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--census", default="artifacts/fem_debt_census.json")
    parser.add_argument("--out", default="artifacts/figs/fem_debt_overview.png")
    parser.add_argument("--dpi", type=int, default=110)
    parser.add_argument("--repo-root", default=None)
    args = parser.parse_args(argv)

    repo_root = pathlib.Path(args.repo_root) if args.repo_root else pathlib.Path(__file__).resolve().parents[1]
    census = json.loads((repo_root / args.census).read_text(encoding="utf-8"))
    per_file = census["per_file"]

    fig, axes = plt.subplots(1, 3, figsize=(14.0, 4.6))
    fig.suptitle(
        "TensorFEM device-readiness debt census — "
        f"numpy_only={census['numpy_only_count']}  sync_points={census['sync_points']}  "
        f"no_device_constructs={census['no_device_constructs']}  host_loops={census['host_loops']}  "
        f"(AST coverage {census['ast_coverage_pct']:.1f} %)",
        fontsize=10,
    )

    # (1) module composition
    ax = axes[0]
    device = census["breakdown"]["device_module_count"]
    numpy_only = census["numpy_only_count"]
    python_only = census["breakdown"]["python_only_modules"]["count"]
    labels = ["device-capable\n(torch imported)", "numpy-only\n(D1 debt)", "python-only\n(host helpers)"]
    values = [device, numpy_only, python_only]
    colours = ["#4c72b0", "#c44e52", "#8c8c8c"]
    bars = ax.bar(labels, values, color=colours)
    for bar, value in zip(bars, values):
        share = 100.0 * value / max(census["files_parsed"], 1)
        ax.text(bar.get_x() + bar.get_width() / 2, value + 2, f"{value}\n({share:.1f} %)",
                ha="center", va="bottom", fontsize=8)
    ax.set_ylabel("modules")
    ax.set_title(f"Module composition ({census['files_parsed']} parsed)", fontsize=9)
    ax.set_ylim(0, max(values) * 1.28)
    ax.tick_params(labelsize=8)

    # (2) worst offenders for missing device= constructors
    ax = axes[1]
    ranked = sorted(per_file, key=lambda r: (-r["no_device_constructs"], r["path"]))[:TOP_N]
    ranked.reverse()
    names = [r["path"].split("/")[-1] for r in ranked]
    ax.barh(names, [r["no_device_constructs"] for r in ranked], color="#c44e52")
    for index, record in enumerate(ranked):
        ax.text(record["no_device_constructs"] + 0.6, index, str(record["no_device_constructs"]),
                va="center", fontsize=7)
    ax.set_xlabel("no_device_constructs (D3)")
    ax.set_title(f"Top {TOP_N} modules: tensor constructors without device=", fontsize=9)
    ax.tick_params(labelsize=7)

    # (3) host loops by iterable kind
    ax = axes[2]
    kinds = sorted(census["breakdown"]["host_loops_by_kind"].items(), key=lambda kv: (-kv[1], kv[0]))[:9]
    kinds.reverse()
    ax.barh([k for k, _ in kinds], [v for _, v in kinds], color="#55a868")
    for index, (_, value) in enumerate(kinds):
        ax.text(value + 3, index, str(value), va="center", fontsize=7)
    ax.set_xlabel("loop statements (D4)")
    ax.set_title("host_loops by iterable kind", fontsize=9)
    ax.tick_params(labelsize=7)

    fig.tight_layout(rect=(0, 0, 1, 0.94))
    out_path = (repo_root / args.out).resolve()
    out_path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out_path, dpi=args.dpi)
    print(f"wrote {out_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())