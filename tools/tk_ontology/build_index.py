#!/usr/bin/env python3
"""Compile the FEM-axis KO index, validate it, and write the artefacts.

Usage (from the repository root):

    python tools/tk_ontology/build_index.py            # write artefacts
    python tools/tk_ontology/build_index.py --check     # compile + validate, write nothing

Artefacts (deterministic: no timestamps, all collections sorted):

    artifacts/ontology/fem_knowledge_index_v1.json
    artifacts/ontology/fem_knowledge_metrics_v1.json
    artifacts/ontology/fem_knowledge_gap_report_v1.md
    artifacts/ontology/fem_knowledge_graph_v1.mmd
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
sys.path.insert(0, str(HERE))

import tk_ontology as onto  # noqa: E402

OUT = ROOT / "artifacts" / "ontology"


def dump(path: Path, payload) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if isinstance(payload, str):
        path.write_text(payload, encoding="utf-8")
    else:
        path.write_text(json.dumps(payload, ensure_ascii=False, indent=2, sort_keys=True) + "\n", encoding="utf-8")


def metrics_markdown(m: dict) -> str:
    """Render the metrics as markdown so a report never hand-copies a number."""
    lines = ["# KO index metrics (generated by tools/tk_ontology/build_index.py)", ""]
    lines.append("## Object counts by form")
    lines.append("")
    lines.append("| form | objects |")
    lines.append("|---|---:|")
    for k, v in m["form_counts"].items():
        lines.append(f"| {k} | {v} |")
    lines.append(f"| **total** | **{m['ko_total']}** |")
    lines.append("")
    lines.append("## Relations (declared edges; inverse twins materialised separately)")
    lines.append("")
    lines.append("| verb | edges |")
    lines.append("|---|---:|")
    for k, v in m["relation_verb_counts"].items():
        lines.append(f"| {k} | {v} |")
    lines.append(f"| **declared total** | **{m['edge_declared']}** |")
    lines.append("")
    lines.append("## Evidence grading")
    lines.append("")
    lines.append("| mechanical grade | artefacts |")
    lines.append("|---|---:|")
    for k, v in sorted(m["evidence_mechanical_grades"].items()):
        lines.append(f"| {k} | {v} |")
    lines.append("")
    lines.append("| declared grade | artefacts |")
    lines.append("|---|---:|")
    for k, v in sorted(m["evidence_declared_grades"].items()):
        lines.append(f"| {k} | {v} |")
    lines.append("")
    g = m["grade_agreement"]
    lines.append(f"Declared-vs-mechanical agreement: **{g['agree']}/{g['comparable']} = {g['rate']:.1%}** "
                 "(denominator = artefacts whose document declares a grade at all).")
    lines.append("")
    lines.append("## Case coverage on the dual axis")
    lines.append("")
    c = m["case_coverage"]
    lines.append("| property | cases | rate |")
    lines.append("|---|---:|---:|")
    lines.append(f"| has re-runnable REAL evidence | {c['with_real_evidence']} / {c['cases']} | {c['rate_real_evidence']:.1%} |")
    lines.append(f"| has a machine-readable criterion | {c['with_criterion']} / {c['cases']} | {c['rate_criterion']:.1%} |")
    lines.append(f"| has a resolved method | {c['with_method']} / {c['cases']} | {c['rate_method']:.1%} |")
    lines.append(f"| has an explicit PASS/FAIL verdict | {c['with_verdict']} / {c['cases']} | {c['rate_verdict']:.1%} |")
    lines.append("")
    lines.append("## Axis histograms")
    lines.append("")
    for label, key in (("method axis", "method_axis_counts"), ("domain axis", "domain_axis_counts")):
        lines.append(f"**{label}**")
        lines.append("")
        lines.append("| value | objects |")
        lines.append("|---|---:|")
        for k, v in m[key].items():
            lines.append(f"| {k} | {v} |")
        lines.append("")
    lines.append(f"Orphan objects (no edge either way): **{len(m['orphan_ko'])}**; "
                 f"dangling edges: **{m['dangling_edges']}**.")
    lines.append("")
    return "\n".join(lines)


def mermaid(index: dict, max_nodes: int = 40) -> str:
    """Small Mermaid excerpt: contracts -> criteria, and the first N cases with their edges."""
    kos = {k["id"]: k for k in index["kos"]}
    lines = ["graph LR"]
    keep = set()
    for k in index["kos"]:
        if k["form"] in ("CONTRACT", "CRITERION"):
            keep.add(k["id"])
    cases = [k["id"] for k in index["kos"] if k["form"] == "CASE"][:max_nodes]
    keep.update(cases)
    for e in index["edges"]:
        if e["derived_inverse"]:
            continue
        if e["subject"] in keep and (e["object"] in keep or e["subject_form"] == "CONTRACT"):
            keep.add(e["object"])
            lines.append(f'  {e["subject"]}["{kos[e["subject"]]["form"]}: {e["subject"]}"]'
                         f' -->|{e["verb"]}| {e["object"]}["{kos[e["object"]]["form"]}: {e["object"]}"]')
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="compile and validate without writing artefacts")
    ap.add_argument("--quiet", action="store_true")
    args = ap.parse_args(argv)

    index = onto.build_index(ROOT)
    problems = onto.validate_index(index, ROOT)
    m = onto.metrics(index)
    if problems:
        for p in problems:
            print("INVALID:", p, file=sys.stderr)
        return 1
    if not args.quiet:
        print(f"KO total={m['ko_total']} forms={m['form_counts']} edges={m['edge_total']}")
        print(f"CASE real-evidence coverage={m['case_coverage']['rate_real_evidence']:.1%} "
              f"criterion={m['case_coverage']['rate_criterion']:.1%} "
              f"method={m['case_coverage']['rate_method']:.1%}")
        print(f"grade agreement={m['grade_agreement']['agree']}/{m['grade_agreement']['comparable']} "
              f"({m['grade_agreement']['rate']:.1%})")
    if args.check:
        return 0
    dump(OUT / "fem_knowledge_index_v1.json", index)
    dump(OUT / "fem_knowledge_metrics_v1.json", m)
    dump(OUT / "fem_knowledge_gap_report_v1.md", onto.gap_report(index, m))
    dump(OUT / "fem_knowledge_metrics_v1.md", metrics_markdown(m))
    dump(OUT / "fem_knowledge_graph_v1.mmd", mermaid(index))
    if not args.quiet:
        print(f"wrote artefacts under {OUT.relative_to(ROOT)}/")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())