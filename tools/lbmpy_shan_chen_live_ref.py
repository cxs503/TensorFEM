"""Live external reference for the two-component Shan-Chen case (lbmpy).

The anchor ``XVAL-LBM-SHAN-CHEN-MCMP-BARYCENTRIC-GUO`` is cross-validated
against the open-source test

    lssfau/lbmpy :: tests/shan_chen/test_shan_chen_two_component.py

whose reference array was generated by the independent C++ implementation
``lbm-principles-practice/code/chapter9/shanchen.cpp`` (nsteps=1000,
nfluids=2, gA=0).  That test does not run unmodified on the installed
``lbmpy 2.0`` / ``pystencils 2.0`` because ``LBStencil.weights`` was replaced
by the module level ``lbmpy.get_weights(stencil)``; the algorithm below is
the same kernel sequence (sync -> force -> u_corr -> collide -> stream ->
u_temp), parameterised so that *new* reference cases can be generated
locally instead of quoting the one published array.

Only the one-symbol API fix is applied; every physics expression (pseudo
potential, interaction force, barycentric velocity, Guo forcing, kernel
ordering) is transcribed from the OSS test.

Usage
-----
    python tools/lbmpy_shan_chen_live_ref.py --n 32 --steps 400 \
        --out docs/assets/lbm_shan_chen_mcmp_barycentric_guo/lbmpy_32x32_g6_400step.json

Requires ``lbmpy`` and ``pystencils`` (optional dependency of the TensorFEM
test bench; the production solver ``tensorfem.lbm_shan_chen_mcmp`` is pure
NumPy and does not need them).
"""
from __future__ import annotations

import argparse
import json
import time
from pathlib import Path


def run_live_reference(n: int = 64, steps: int = 1000, g_ab: float = 6.0,
                       omega_a: float = 1.0, omega_b: float = 1.0,
                       rho0: float = 1.0, rho_lo: float = 0.1,
                       rho_hi: float = 0.9, record=None) -> dict:
    """Run the OSS Shan-Chen two-component algorithm on this machine.

    Returns the gathered ``rho_a`` / ``rho_b`` profiles (one lattice line,
    periodic domain, which is uniform along the transverse direction) plus
    provenance so that the numbers can be traced back to a live execution.
    """
    import lbmpy
    import numpy as np
    import pystencils as ps
    import sympy as sp

    from lbmpy.enums import Stencil
    from lbmpy import LBMConfig, ForceModel, create_lb_update_rule
    from lbmpy.macroscopic_value_kernels import macroscopic_values_setter
    from lbmpy.creationfunctions import create_stream_pull_with_output_kernel

    stencil = lbmpy.LBStencil(Stencil.D2Q9)
    weights = lbmpy.get_weights(stencil)          # OSS: stencil.weights (pre-2.0 API)
    dim = stencil.D
    dh = ps.create_data_handling((n,) * dim, periodicity=True,
                                 default_target=ps.Target.CPU)

    src_a = dh.add_array('src_a', values_per_cell=stencil.Q)
    dst_a = dh.add_array_like('dst_a', 'src_a')
    src_b = dh.add_array('src_b', values_per_cell=stencil.Q)
    dst_b = dh.add_array_like('dst_b', 'src_b')

    rho_a_f = dh.add_array('rho_a')
    rho_b_f = dh.add_array('rho_b')
    u_a = dh.add_array('u_a', values_per_cell=stencil.D)
    u_b = dh.add_array('u_b', values_per_cell=stencil.D)
    u_bary = dh.add_array_like('u_bary', u_a.name)
    f_a = dh.add_array('f_a', values_per_cell=stencil.D)
    f_b = dh.add_array_like('f_b', f_a.name)

    def psi(dens):
        return rho0 * (1. - sp.exp(-dens / rho0))

    zero_vec = sp.Matrix([0] * stencil.D)
    force_a = zero_vec
    for factor, rho in zip([0.0, g_ab], [rho_a_f, rho_b_f]):
        force_a += sum((psi(rho[d]) * w_d * sp.Matrix(d)
                        for d, w_d in zip(stencil, weights)), zero_vec) * psi(rho_a_f.center) * -1 * factor
    force_b = zero_vec
    for factor, rho in zip([g_ab, 0.0], [rho_a_f, rho_b_f]):
        force_b += sum((psi(rho[d]) * w_d * sp.Matrix(d)
                        for d, w_d in zip(stencil, weights)), zero_vec) * psi(rho_b_f.center) * -1 * factor

    f_expressions = ps.AssignmentCollection([
        ps.Assignment(f_a.center_vector, force_a),
        ps.Assignment(f_b.center_vector, force_b),
    ])
    u_temp = ps.AssignmentCollection(ps.Assignment(
        u_bary.center_vector,
        (rho_a_f.center * u_a.center_vector - f_a.center_vector / 2
         + rho_b_f.center * u_b.center_vector - f_b.center_vector / 2)
        / (rho_a_f.center + rho_b_f.center)))
    u_corr = ps.AssignmentCollection(ps.Assignment(
        u_bary.center_vector,
        u_bary.center_vector + (f_a.center_vector / 2 + f_b.center_vector / 2)
        / (rho_a_f.center + rho_b_f.center)))

    cfg_a = LBMConfig(stencil=stencil, relaxation_rate=omega_a, compressible=True,
                      velocity_input=u_bary, density_input=rho_a_f,
                      force_model=ForceModel.GUO, force=f_a, kernel_type='collide_only')
    cfg_b = LBMConfig(stencil=stencil, relaxation_rate=omega_b, compressible=True,
                      velocity_input=u_bary, density_input=rho_b_f,
                      force_model=ForceModel.GUO, force=f_b, kernel_type='collide_only')
    collision_a = create_lb_update_rule(lbm_config=cfg_a, optimization={'symbolic_field': src_a})
    collision_b = create_lb_update_rule(lbm_config=cfg_b, optimization={'symbolic_field': src_b})
    stream_a = create_stream_pull_with_output_kernel(collision_a.method, src_a, dst_a,
                                                     {'density': rho_a_f, 'velocity': u_a})
    stream_b = create_stream_pull_with_output_kernel(collision_b.method, src_b, dst_b,
                                                     {'density': rho_b_f, 'velocity': u_b})

    config = ps.CreateKernelConfig(target=dh.default_target)
    k_stream_a = ps.create_kernel(stream_a, config=config).compile()
    k_stream_b = ps.create_kernel(stream_b, config=config).compile()
    k_coll_a = ps.create_kernel(collision_a, config=config).compile()
    k_coll_b = ps.create_kernel(collision_b, config=config).compile()
    k_force = ps.create_kernel(f_expressions, config=config).compile()
    k_utemp = ps.create_kernel(u_temp, config=config).compile()
    k_ucorr = ps.create_kernel(u_corr, config=config).compile()

    init_a = macroscopic_values_setter(collision_a.method, velocity=(0, 0),
                                       pdfs=src_a.center_vector, density=rho_a_f.center)
    init_b = macroscopic_values_setter(collision_b.method, velocity=(0, 0),
                                       pdfs=src_b.center_vector, density=rho_b_f.center)
    k_init_a = ps.create_kernel(init_a, ghost_layers=0).compile()
    k_init_b = ps.create_kernel(init_b, ghost_layers=0).compile()

    sync_pdfs = dh.synchronization_function([src_a.name, src_b.name])
    sync_rhos = dh.synchronization_function([rho_a_f.name, rho_b_f.name])

    dh.fill(rho_a_f.name, rho_lo, slice_obj=ps.make_slice[:, :0.5])
    dh.fill(rho_a_f.name, rho_hi, slice_obj=ps.make_slice[:, 0.5:])
    dh.fill(rho_b_f.name, rho_hi, slice_obj=ps.make_slice[:, :0.5])
    dh.fill(rho_b_f.name, rho_lo, slice_obj=ps.make_slice[:, 0.5:])
    dh.fill(u_a.name, 0.0)
    dh.fill(u_b.name, 0.0)
    dh.fill(f_a.name, 0.0)
    dh.fill(f_b.name, 0.0)
    dh.run_kernel(k_utemp)
    dh.run_kernel(k_init_a)
    dh.run_kernel(k_init_b)

    t0 = time.time()
    for i in range(steps):
        sync_rhos()
        dh.run_kernel(k_force)
        dh.run_kernel(k_ucorr)
        dh.run_kernel(k_coll_a)
        dh.run_kernel(k_coll_b)
        sync_pdfs()
        dh.run_kernel(k_stream_a)
        dh.run_kernel(k_stream_b)
        dh.run_kernel(k_utemp)
        dh.swap(src_a.name, dst_a.name)
        dh.swap(src_b.name, dst_b.name)
        if record is not None and (i + 1) in record:
            record[i + 1] = {
                "rho_a": [float(v) for v in np.array(dh.gather_array(rho_a_f.name)[0])],
                "rho_b": [float(v) for v in np.array(dh.gather_array(rho_b_f.name)[0])],
            }

    return {
        "harness": "tools/lbmpy_shan_chen_live_ref.py",
        "origin": "lssfau/lbmpy tests/shan_chen/test_shan_chen_two_component.py "
                  "(algorithm transcribed verbatim; only the lbmpy>=2.0 "
                  "get_weights API fix applied)",
        "params": {"n": n, "steps": steps, "g_ab": g_ab, "omega_a": omega_a,
                   "omega_b": omega_b, "rho0": rho0,
                   "rho_a_init": [rho_lo, rho_hi], "rho_b_init": [rho_hi, rho_lo],
                   "periodic": True},
        "lbmpy_version": getattr(lbmpy, "__version__", "unknown"),
        "pystencils_version": getattr(ps, "__version__", "unknown"),
        "wall_time_s": round(time.time() - t0, 3),
        "rho_a_profile": [float(v) for v in np.array(dh.gather_array(rho_a_f.name)[0])],
        "rho_b_profile": [float(v) for v in np.array(dh.gather_array(rho_b_f.name)[0])],
    }


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--n", type=int, default=64)
    ap.add_argument("--steps", type=int, default=1000)
    ap.add_argument("--g-ab", type=float, default=6.0)
    ap.add_argument("--out", type=str, default="")
    args = ap.parse_args()
    res = run_live_reference(n=args.n, steps=args.steps, g_ab=args.g_ab)
    text = json.dumps(res, indent=1)
    if args.out:
        path = Path(args.out)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text + "\n")
        print(f"wrote {path} (rho_a[:4]={['%.6f' % v for v in res['rho_a_profile'][:4]]})")
    else:
        print(text)


if __name__ == "__main__":
    main()