@dataclass(frozen=True)
class SatohParams:
    """Parameters for 1D Satoh thermo-elasto-plastic problem.

    A bar constrained at both ends (total strain = 0) is heated then cooled.
    Temperature-dependent yield stress drives plastic flow.

    Attributes
    ----------
    E : float
        Young's modulus [Pa].
    alpha : float
        Coefficient of thermal expansion [1/K].
    sigma_y0 : float
        Yield stress at reference temperature [Pa].
    T_ref : float
        Reference temperature [K].
    T_max : float
        Maximum temperature [K].
    n_steps : int
        Number of temperature steps.
    hardening : float
        Isotropic hardening modulus [Pa].
    sigma_y_func : optional
        Custom temperature-dependent yield function sigma_y(T).
    """
    E: float = 210e9           # Pa (steel)
    alpha: float = 1.2e-5      # 1/K
    sigma_y0: float = 350e6    # Pa (DH36 at room temp)
    T_ref: float = 293.15      # K
    T_max: float = 873.15      # K (600°C)
    n_steps: int = 200
    hardening: float = 1e9     # Pa
    sigma_y_func: Optional[callable] = None


def _default_sigma_y(T: float, params: SatohParams) -> float:
    """Default temperature-dependent yield stress (linear degradation).

    sigma_y(T) = sigma_y0 * max(0.05, 1.0 - 0.7*(T - T_ref)/(T_melt - T_ref))
    where T_melt ≈ 1800 K for steel.
    """
    T_melt = 1800.0
    ratio = max(0.05, 1.0 - 0.7 * (T - params.T_ref) / (T_melt - params.T_ref))
    return params.sigma_y0 * ratio


def satoh_1d_thermoplastic(
    params: Optional[SatohParams] = None,
    temperature_history: Optional[List[float]] = None,
) -> Dict:
    """Solve 1D Satoh thermo-elasto-plastic problem.

    Constrained bar (eps_total = 0):
        eps_total = eps_el + eps_pl + eps_th = 0
        sigma = E * eps_el
        eps_th = alpha * (T - T_ref)

    Yield condition: |sigma| = sigma_y(T) + H * alpha_cum
    Flow rule: associative (1D: d_eps_pl = d_gamma * sign(sigma))

    Returns dict with temperature, stress, plastic strain histories.
    """
    if params is None:
        params = SatohParams()

    sigma_y_func = params.sigma_y_func or (lambda T: _default_sigma_y(T, params))

    # Temperature history: heat up then cool down
    if temperature_history is None:
        T_up = torch.linspace(params.T_ref, params.T_max, params.n_steps // 2)
        T_down = torch.linspace(params.T_max, params.T_ref, params.n_steps // 2)
        T_hist = torch.cat([T_up, T_down[1:]])
    else:
        T_hist = torch.tensor(temperature_history, dtype=_DTYPE)

    n = len(T_hist)
    stress = torch.zeros(n, dtype=_DTYPE)
    eps_pl = torch.zeros(n, dtype=_DTYPE)
    eps_el = torch.zeros(n, dtype=_DTYPE)
    alpha_cum = torch.zeros(n, dtype=_DTYPE)  # cumulative plastic strain

    # Initial state
    sigma = torch.tensor(0.0, dtype=_DTYPE)
    ep = torch.tensor(0.0, dtype=_DTYPE)
    ac = torch.tensor(0.0, dtype=_DTYPE)

    for i in range(n):
        T = float(T_hist[i])
        eps_th = params.alpha * (T - params.T_ref)

        # Trial: eps_el_trial = -eps_th - ep (from eps_total = 0)
        eps_el_trial = -eps_th - float(ep)
        sigma_trial = params.E * eps_el_trial

        # Yield check
        sy = sigma_y_func(T) + float(params.hardening) * float(ac)
        f = abs(sigma_trial) - sy

        if f <= 0:
            # Elastic
            sigma = torch.tensor(sigma_trial, dtype=_DTYPE)
        else:
            # Plastic: return mapping
            dgamma = f / (params.E + params.hardening)
            direction = 1.0 if sigma_trial > 0 else -1.0
            ep = ep + dgamma * direction
            ac = ac + dgamma
            sigma = torch.tensor(sigma_trial - params.E * dgamma * direction, dtype=_DTYPE)

        stress[i] = sigma
        eps_pl[i] = ep
        eps_el[i] = -eps_th - float(ep)
        alpha_cum[i] = ac

    return {
        "T_hist": T_hist,
        "stress": stress,
        "eps_pl": eps_pl,
        "eps_el": eps_el,
        "alpha_cum": alpha_cum,
        "residual_stress": float(stress[-1]),
        "residual_plastic_strain": float(eps_pl[-1]),
        "max_compressive_stress": float(stress.min()),
        "max_tensile_stress": float(stress.max()),
    }


def satoh_residual_stress_profile(
    x_coords: torch.Tensor,
    peak_temperature: torch.Tensor,
    params: Optional[SatohParams] = None,
) -> torch.Tensor:
    """Compute residual stress profile across a weld cross-section.

    Each point at coordinate x experienced a peak temperature T_peak(x).
    The residual stress at each point is computed by running the Satoh
    cycle with that peak temperature.

    Parameters
    ----------
    x_coords : Tensor
        Spatial coordinates across the weld [m].
    peak_temperature : Tensor
        Peak temperature at each coordinate [K].
    params : SatohParams, optional

    Returns
    -------
    Tensor
        Residual stress at each coordinate [Pa].
    """
    if params is None:
        params = SatohParams()

    n = len(x_coords)
    residual = torch.zeros(n, dtype=_DTYPE)

    for i in range(n):
        T_peak = float(peak_temperature[i])
        if T_peak <= params.T_ref + 1.0:
            # No thermal cycle
            residual[i] = 0.0
            continue

        # Simple thermal cycle: heat to T_peak, cool to T_ref
        T_up = torch.linspace(params.T_ref, T_peak, 50)
        T_down = torch.linspace(T_peak, params.T_ref, 50)
        T_hist = torch.cat([T_up, T_down[1:]]).tolist()

        result = satoh_1d_thermoplastic(params, T_hist)
        residual[i] = result["residual_stress"]

    return residual


def verify_satoh_1d(
    params: Optional[SatohParams] = None,
    tol_stress: float = 0.03,
    tol_plastic_width: float = 0.05,
) -> Dict:
    """Verify Satoh 1D solution against analytical expectations.

    Checks:
    1. Maximum compressive stress during heating ≈ -sigma_y(T_max)
    2. Residual stress after cooling ≈ +sigma_y(T_ref) (tensile)
    3. Plastic zone exists (cumulative plastic strain > 0)
    4. Energy consistency: plastic work = integral of sigma * d_eps_pl

    Returns dict with verification results.
    """
    if params is None:
        params = SatohParams()

    result = satoh_1d_thermoplastic(params)

    sigma_y_ref = _default_sigma_y(params.T_ref, params)
    sigma_y_max = _default_sigma_y(params.T_max, params)

    # Check 1: max compressive stress should be close to -sigma_y at some T
    max_comp = result["max_compressive_stress"]
    # The max compression occurs when yield is reached during heating
    # It should be approximately -sigma_y(T) at the temperature where yielding starts
    expected_comp = -sigma_y_ref  # at minimum, should reach room-temp yield
    comp_ratio = abs(max_comp) / sigma_y_ref

    # Check 2: residual stress should be tensile
    res_stress = result["residual_stress"]
    is_tensile = res_stress > 0

    # Check 3: plastic strain accumulated
    has_plasticity = result["residual_plastic_strain"] != 0.0

    # Check 4: compute plastic work
    T_hist = result["T_hist"]
    stress_hist = result["stress"]
    eps_pl_hist = result["eps_pl"]
    d_eps_pl = torch.diff(eps_pl_hist)
    sigma_mid = 0.5 * (stress_hist[:-1] + stress_hist[1:])
    plastic_work = float(torch.sum(sigma_mid * d_eps_pl))

    return {
        "max_compressive_stress_Pa": max_comp,
        "expected_yield_Pa": sigma_y_ref,
        "compression_ratio": comp_ratio,
        "compression_check": comp_ratio >= 0.90,
        "residual_stress_Pa": res_stress,
        "residual_is_tensile": is_tensile,
        "has_plasticity": has_plasticity,
        "plastic_work_J_per_m3": plastic_work,
        "residual_plastic_strain": result["residual_plastic_strain"],
        "all_checks_pass": (comp_ratio >= 0.90 and is_tensile and has_plasticity),
    }


