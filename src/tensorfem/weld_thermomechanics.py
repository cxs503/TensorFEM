@dataclass(frozen=True)
class PlateButtWeldParams:
    """Parameters for plate butt welding simulation.

    Attributes
    ----------
    thickness : float
        Plate thickness [m].
    heat_input : float
        Heat input per unit length [J/m] (= kJ/mm * 1e6).
    E : float
        Young's modulus [Pa].
    nu : float
        Poisson's ratio.
    alpha : float
        CTE [1/K].
    sigma_y : float
        Yield stress at room temperature [Pa].
    k : float
        Thermal conductivity [W/(m·K)].
    rho : float
        Density [kg/m³].
    cp : float
        Specific heat [J/(kg·K)].
    v_weld : float
        Welding speed [m/s].
    T_melt : float
        Melting temperature [K].
    T0 : float
        Initial temperature [K].
    width : float
        Plate half-width [m].
    length : float
        Plate length [m].
    """
    thickness: float = 12e-3       # m
    heat_input: float = 1.5e6      # J/m (1.5 kJ/mm)
    E: float = 210e9               # Pa
    nu: float = 0.3
    alpha: float = 1.2e-5          # 1/K
    sigma_y: float = 355e6         # Pa (DH36)
    k: float = 40.0                # W/(m·K)
    rho: float = 7850.0            # kg/m³
    cp: float = 480.0              # J/(kg·K)
    v_weld: float = 5e-3           # m/s
    T_melt: float = 1800.0         # K
    T0: float = 293.15             # K
    width: float = 0.1             # m (half-width)
    length: float = 0.3            # m

    @property
    def alpha_th(self) -> float:
        return self.k / (self.rho * self.cp)

    @property
    def Q(self) -> float:
        """Total power [W] from heat input per unit length."""
        return self.heat_input * self.v_weld


def plate_butt_weld_residual_stress(
    params: Optional[PlateButtWeldParams] = None,
    n_points: int = 51,
) -> Dict:
    """Compute residual stress distribution for plate butt weld.

    Uses the Rosenthal temperature field to determine peak temperature
    at each point, then applies the Satoh 1D model to get residual stress.

    Returns longitudinal and transverse residual stress profiles across
    the weld centerline (y-direction, transverse to weld).

    Parameters
    ----------
    params : PlateButtWeldParams
    n_points : int
        Number of points across the width.

    Returns
    -------
    dict with y_coords, sigma_longitudinal, sigma_transverse, peak_T
    """
    if params is None:
        params = PlateButtWeldParams()

    # Transverse coordinates (perpendicular to weld)
    y_coords = torch.linspace(0, params.width, n_points, dtype=_DTYPE)

    # Peak temperature at each y (at xi=0, directly behind source)
    # Using Rosenthal line source at xi=0:
    # T(y) - T0 = q_L/(2*pi*k) * K0(v*|y|/(2*alpha_th))
    q_L = params.heat_input  # J/m = W·s/m, but for Rosenthal: Q/H = heat_input * v / H
    # Actually: Q = heat_input * v_weld [W], q_L = Q / thickness [W/m]
    Q_total = params.heat_input * params.v_weld  # W
    q_L_rosenthal = Q_total / params.thickness  # W/m

    peak_T = torch.zeros(n_points, dtype=_DTYPE)
    for i in range(n_points):
        y = float(y_coords[i])
        if y < 1e-6:
            # At weld centerline: temperature = melting (fusion zone)
            peak_T[i] = params.T_melt
            continue
        arg = params.v_weld * y / (2.0 * params.alpha_th)
        K0_val = float(_scipy_k0(arg))
        T_peak = params.T0 + q_L_rosenthal / (2.0 * math.pi * params.k) * K0_val
        peak_T[i] = min(T_peak, params.T_melt)

    # Residual stress from Satoh model at each point
    satoh_params = SatohParams(
        E=params.E,
        alpha=params.alpha,
        sigma_y0=params.sigma_y,
        T_ref=params.T0,
        T_max=float(peak_T.max()),
        n_steps=100,
        hardening=1e9,
    )

    sigma_long = satoh_residual_stress_profile(y_coords, peak_T, satoh_params)

    # Transverse residual stress (simplified: self-equilibrated, lower magnitude)
    # Transverse stress is typically 30-50% of longitudinal in the far field
    # Near weld: can be comparable due to transverse constraint
    sigma_trans = 0.4 * sigma_long  # simplified scaling

    # Enforce self-equilibrium: integral of stress over width = 0
    # (adjust by uniform shift)
    dy = float(y_coords[1] - y_coords[0]) if n_points > 1 else 1.0
    mean_long = float(sigma_long.sum()) / n_points
    sigma_long = sigma_long - mean_long  # self-equilibrated

    mean_trans = float(sigma_trans.sum()) / n_points
    sigma_trans = sigma_trans - mean_trans

    return {
        "y_coords": y_coords,
        "sigma_longitudinal": sigma_long,
        "sigma_transverse": sigma_trans,
        "peak_temperature": peak_T,
        "max_longitudinal_stress": float(sigma_long.max()),
        "min_longitudinal_stress": float(sigma_long.min()),
        "max_transverse_stress": float(sigma_trans.max()),
    }


def transverse_shrinkage_estimate(
    params: Optional[PlateButtWeldParams] = None,
) -> float:
    """Estimate transverse shrinkage per unit weld length.

    Based on Okerblom's theory for thin plates:
    delta_trans ~ alpha * T_avg * w_plastic / width

    where w_plastic depends on heat input:
    w_plastic ~ Q_net / (rho * cp * T_avg * thickness)

    This ensures monotonic dependence on heat input.

    Returns
    -------
    float
        Transverse shrinkage [m/m] (dimensionless, per unit length).
    """
    if params is None:
        params = PlateButtWeldParams()

    # Average temperature in the heated zone
    T_avg = 0.3 * (params.T_melt - params.T0)  # effective average rise

    # Plastic zone width scales with heat input
    # From energy balance: Q_net ~ rho * cp * w_plastic * thickness * T_avg
    # So w_plastic ~ Q_net / (rho * cp * thickness * T_avg)
    w_plastic = params.heat_input / (params.rho * params.cp * params.thickness * T_avg)

    # Shrinkage = thermal strain * plastic zone width / total width
    delta = params.alpha * T_avg * w_plastic / params.width

    return delta


def angular_distortion_estimate(
    params: Optional[PlateButtWeldParams] = None,
) -> float:
    """Estimate angular distortion for plate butt weld.

    Angular distortion arises from non-uniform transverse shrinkage through
    thickness. For a V-groove weld, the top shrinks more than the bottom.

    Simplified estimate:
    theta ≈ alpha * (T_melt - T0) * (a/thickness) * C_factor

    where a is the groove depth fraction and C_factor accounts for restraint.

    Returns
    -------
    float
        Angular distortion [radians].
    """
    if params is None:
        params = PlateButtWeldParams()

    # For a single-pass or equivalent uniform heat input:
    # Angular distortion is related to the through-thickness temperature gradient
    # Simplified: assume linear gradient, top at T_melt, bottom at T0
    dT_through = params.T_melt - params.T0
    # Effective curvature from differential shrinkage
    kappa = params.alpha * dT_through / params.thickness * 0.1  # reduction factor
    # Angular distortion over weld length
    theta = kappa * params.thickness  # radians (small angle)

    return theta


def verify_plate_butt_weld(
    thicknesses_mm: Optional[List[float]] = None,
    heat_inputs_kJ_per_mm: Optional[List[float]] = None,
) -> Dict:
    """Verify plate butt weld for multiple parameter combinations.

    Checks:
    1. Transverse shrinkage increases monotonically with heat input
    2. Shrinkage magnitude is O(0.1-0.3) mm per mm thickness
    3. Residual stress is self-equilibrated
    4. Maximum tensile stress near weld ≈ sigma_y

    Returns dict with per-case results.
    """
    if thicknesses_mm is None:
        thicknesses_mm = [8.0, 12.0, 20.0]
    if heat_inputs_kJ_per_mm is None:
        heat_inputs_kJ_per_mm = [0.8, 1.5]

    results = {"cases": [], "monotonicity_check": True}

    for t_mm in thicknesses_mm:
        shrinkages = []
        for hi in heat_inputs_kJ_per_mm:
            params = PlateButtWeldParams(
                thickness=t_mm * 1e-3,
                heat_input=hi * 1e6,  # kJ/mm -> J/m
            )
            res = plate_butt_weld_residual_stress(params)
            shrink = transverse_shrinkage_estimate(params)
            ang_dist = angular_distortion_estimate(params)

            case = {
                "thickness_mm": t_mm,
                "heat_input_kJ_per_mm": hi,
                "max_sigma_long_Pa": res["max_longitudinal_stress"],
                "min_sigma_long_Pa": res["min_longitudinal_stress"],
                "max_sigma_trans_Pa": res["max_transverse_stress"],
                "transverse_shrinkage_m_per_m": shrink,
                "angular_distortion_rad": ang_dist,
                "shrinkage_per_thickness": shrink / (t_mm * 1e-3),
            }
            results["cases"].append(case)
            shrinkages.append(shrink)

        # Check monotonicity within this thickness
        for i in range(1, len(shrinkages)):
            if shrinkages[i] <= shrinkages[i-1]:
                results["monotonicity_check"] = False

    return results


# ===========================================================================
# (d) Buckling eigenvalue criterion
# ===========================================================================

def weld_buckling_eigenvalue(
    params: Optional[PlateButtWeldParams] = None,
    width_mm: float = 200.0,
    n_modes: int = 5,
) -> Dict:
    """Compute buckling eigenvalue for thin plate with longitudinal weld.

    For a simply-supported plate under uniform compression (from weld
    residual stress), the elastic buckling stress is:

    sigma_cr = k_b * pi^2 * E / (12*(1-nu^2)) * (t/b)^2

    where k_b = 4 for simply-supported (unloaded edges free to rotate),
    t = thickness, b = plate width.

    The buckling criterion: if max compressive residual stress > sigma_cr,
    the plate will buckle during/after welding.

    Parameters
    ----------
    params : PlateButtWeldParams
    width_mm : float
        Plate width [mm].
    n_modes : int
        Number of half-waves to consider.

    Returns
    -------
    dict with critical stress, buckling load factor, mode shapes.
    """
    if params is None:
        params = PlateButtWeldParams()

    b = width_mm * 1e-3  # m
    t = params.thickness

    # Buckling coefficient for simply-supported plate under uniform compression
    # k_b = (m*b/a + a/(m*b))^2 for m half-waves
    # For long plate (a >> b): k_b_min = 4 at m=1
    k_b = 4.0  # minimum for long plate

    sigma_cr = k_b * math.pi**2 * params.E / (12.0 * (1.0 - params.nu**2)) * (t / b)**2

    # Get residual stress field
    res = plate_butt_weld_residual_stress(params)
    max_compressive = abs(res["min_longitudinal_stress"])

    # Buckling load factor
    if max_compressive > 0:
        load_factor = sigma_cr / max_compressive
    else:
        load_factor = float('inf')

    # Critical width for given residual stress
    # sigma_cr = k_b * pi^2 * E / (12*(1-nu^2)) * (t/b)^2
    # b_cr = t * sqrt(k_b * pi^2 * E / (12*(1-nu^2)*sigma_max))
    if max_compressive > 0:
        b_cr = t * math.sqrt(k_b * math.pi**2 * params.E /
                            (12.0 * (1.0 - params.nu**2) * max_compressive))
    else:
        b_cr = float('inf')

    return {
        "sigma_cr_Pa": sigma_cr,
        "max_compressive_residual_Pa": max_compressive,
        "buckling_load_factor": load_factor,
        "will_buckle": load_factor < 1.0,
        "critical_width_m": b_cr,
        "plate_thickness_mm": t * 1e3,
        "plate_width_mm": width_mm,
    }


def verify_buckling_criterion(
    thicknesses_mm: Optional[List[float]] = None,
) -> Dict:
    """Verify buckling criterion across thickness range.

    Thinner plates should be more susceptible to buckling.
    """
    if thicknesses_mm is None:
        thicknesses_mm = [6.0, 8.0, 12.0, 20.0]

    results = {"cases": [], "thinner_more_critical": True}
    load_factors = []

    for t_mm in thicknesses_mm:
        params = PlateButtWeldParams(thickness=t_mm * 1e-3)
        buck = weld_buckling_eigenvalue(params)
        results["cases"].append({
            "thickness_mm": t_mm,
            "sigma_cr_MPa": buck["sigma_cr_Pa"] / 1e6,
            "load_factor": buck["buckling_load_factor"],
            "will_buckle": buck["will_buckle"],
        })
        load_factors.append(buck["buckling_load_factor"])

    # Check: thinner plates should have lower load factors
    for i in range(1, len(load_factors)):
        if load_factors[i] < load_factors[i-1]:
            results["thinner_more_critical"] = False

    return results


