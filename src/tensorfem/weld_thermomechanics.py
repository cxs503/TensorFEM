@dataclass(frozen=True)
class RosenthalParams:
    """Parameters for Rosenthal moving heat source.

    Attributes
    ----------
    Q : float
        Heat input power [W].
    v : float
        Travel speed [m/s].
    k : float
        Thermal conductivity [W/(m·K)].
    alpha_th : float
        Thermal diffusivity [m²/s].
    T0 : float
        Initial/preheat temperature [K].
    source_type : str
        'point' for 3D semi-infinite, 'line' for 2D thin plate.
    H : float
        Plate thickness [m] (for line source).
    """
    Q: float = 3000.0          # W
    v: float = 5e-3            # m/s (5 mm/s)
    k: float = 40.0            # W/(m·K) — DH36 steel
    alpha_th: float = 1.2e-5   # m²/s
    T0: float = 293.15         # K (20°C)
    source_type: str = "line"
    H: float = 12e-3           # m (12 mm plate)


def roenthal_point_source(
    xi: float, y: float, z: float, params: RosenthalParams
) -> float:
    """Rosenthal point source quasi-steady temperature.

    T(xi, y, z) - T0 = Q / (2*pi*k*r) * exp(-v*(r + xi) / (2*alpha_th))

    where xi = x - v*t (moving coordinate), r = sqrt(xi^2 + y^2 + z^2).

    Parameters
    ----------
    xi : float
        Coordinate along welding direction relative to source [m].
    y, z : float
        Transverse and depth coordinates [m].
    params : RosenthalParams

    Returns
    -------
    float
        Temperature [K].
    """
    r = math.sqrt(xi**2 + y**2 + z**2)
    if r < 1e-15:
        return float('inf')  # singularity at source
    T = params.T0 + params.Q / (2.0 * math.pi * params.k * r) * \
        math.exp(-params.v * (r + xi) / (2.0 * params.alpha_th))
    return T


def roenthal_line_source_2d(
    xi: float, y: float, params: RosenthalParams
) -> float:
    """Rosenthal line source (thin plate) quasi-steady temperature.

    T(xi, y) - T0 = q_L / (2*pi*k) * exp(-v*xi/(2*alpha_th)) * K0(v*r/(2*alpha_th))

    where q_L = Q/H [W/m] is heat input per unit length,
    r = sqrt(xi^2 + y^2), K0 is modified Bessel function of 2nd kind.

    Parameters
    ----------
    xi : float
        Coordinate along welding direction relative to source [m].
    y : float
        Transverse coordinate [m].
    params : RosenthalParams

    Returns
    -------
    float
        Temperature [K].
    """
    r = math.sqrt(xi**2 + y**2)
    if r < 1e-15:
        return float('inf')
    q_L = params.Q / params.H  # W/m
    arg = params.v * r / (2.0 * params.alpha_th)
    # K0 via torch for consistency
    K0_val = float(_scipy_k0(arg))
    T = params.T0 + q_L / (2.0 * math.pi * params.k) * \
        math.exp(-params.v * xi / (2.0 * params.alpha_th)) * K0_val
    return T


def isotherm_half_width_line_source(
    Tc: float, params: RosenthalParams, xi: float = 0.0
) -> float:
    """Compute isotherm half-width w at cross-section xi for line source.

    At xi = const, the temperature is:
    T(y) - T0 = q_L/(2*pi*k) * exp(-v*xi/(2*alpha)) * K0(v*r/(2*alpha))
    where r = sqrt(xi^2 + y^2).

    Setting T = Tc and solving for |y| = w:
    K0(v*sqrt(xi^2 + w^2)/(2*alpha)) = 2*pi*k*(Tc - T0) / (q_L * exp(-v*xi/(2*alpha)))

    We invert K0 numerically using bisection.

    Parameters
    ----------
    Tc : float
        Critical temperature (e.g., melting point) [K].
    params : RosenthalParams
    xi : float
        Cross-section position [m].

    Returns
    -------
    float
        Isotherm half-width [m].
    """
    q_L = params.Q / params.H
    exp_factor = math.exp(-params.v * xi / (2.0 * params.alpha_th))
    rhs = 2.0 * math.pi * params.k * (Tc - params.T0) / (q_L * exp_factor)

    if rhs <= 0:
        return 0.0

    # K0 is monotonically decreasing; K0(x) -> inf as x->0, K0(x) -> 0 as x->inf
    # We need K0(v*r/(2*alpha)) = rhs where r = sqrt(xi^2 + w^2)
    # Bisection on w in [1e-8, 0.1] m
    w_lo, w_hi = 1e-8, 0.1
    coeff = params.v / (2.0 * params.alpha_th)

    for _ in range(200):
        w_mid = 0.5 * (w_lo + w_hi)
        r_mid = math.sqrt(xi**2 + w_mid**2)
        K0_mid = float(_scipy_k0(coeff * r_mid))
        if K0_mid > rhs:
            w_lo = w_mid
        else:
            w_hi = w_mid
        if (w_hi - w_lo) < 1e-12:
            break

    return 0.5 * (w_lo + w_hi)


def verify_roenthal_isotherms(
    params: Optional[RosenthalParams] = None,
    Tc_values: Optional[List[float]] = None,
    n_sections: int = 3,
) -> Dict:
    """Verify Rosenthal isotherm half-widths against closed-form inversion.

    Checks that the temperature field evaluated at (xi, w, 0) equals Tc
    within tolerance at multiple cross-sections and temperatures.

    Returns dict with per-section relative errors.
    """
    if params is None:
        params = RosenthalParams()
    if Tc_values is None:
        Tc_values = [600.0, 800.0, 1000.0]  # K (lowered to ensure isotherms exist)

    results = {"sections": [], "max_rel_error": 0.0}
    # Use smaller xi range to ensure isotherms exist
    xi_values = [-0.002, 0.0, 0.002]  # m: ahead, at, behind source

    for xi in xi_values[:n_sections]:
        for Tc in Tc_values:
            # Check if isotherm exists at this cross-section
            T_max_at_xi = roenthal_line_source_2d(xi, 0.0, params)
            if T_max_at_xi < Tc:
                # Isotherm doesn't exist here (temperature too low)
                continue
            
            w = isotherm_half_width_line_source(Tc, params, xi)
            if w < 1e-10:
                continue
            # Verify: T(xi, w) should equal Tc
            T_computed = roenthal_line_source_2d(xi, w, params)
            rel_err = abs(T_computed - Tc) / (Tc - params.T0) if Tc > params.T0 else 0.0
            results["sections"].append({
                "xi_m": xi,
                "Tc_K": Tc,
                "w_m": w,
                "T_computed_K": T_computed,
                "rel_error": rel_err,
            })
            results["max_rel_error"] = max(results["max_rel_error"], rel_err)

    return results


