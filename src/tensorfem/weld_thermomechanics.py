# Negative control: elastic limit
# ===========================================================================

def verify_negative_control_elastic(
    multiplier: float = 10.0,
) -> Dict:
    """Negative control: when yield stress is 10× normal, response is pure elastic.

    With sigma_y = 10 * 355 MPa = 3550 MPa, the material should never yield
    for typical welding thermal strains, and the residual stress should be
    zero (purely elastic recovery).

    Returns dict with verification results.
    """
    # Normal case
    params_normal = SatohParams(sigma_y0=355e6)
    res_normal = satoh_1d_thermoplastic(params_normal)

    # High yield case (should be elastic)
    params_high = SatohParams(sigma_y0=multiplier * 355e6)
    res_high = satoh_1d_thermoplastic(params_high)

    # Check: high yield case should have zero plastic strain
    has_plasticity_high = abs(res_high["residual_plastic_strain"]) > 1e-15

    # Check: residual stress in high yield case should be near zero
    # (elastic recovery is complete)
    residual_stress_high = abs(res_high["residual_stress"])

    # Check: normal case should have significant plastic strain
    has_plasticity_normal = abs(res_normal["residual_plastic_strain"]) > 1e-8

    return {
        "multiplier": multiplier,
        "high_yield_plastic_strain": res_high["residual_plastic_strain"],
        "high_yield_residual_stress_Pa": res_high["residual_stress"],
        "normal_plastic_strain": res_normal["residual_plastic_strain"],
        "normal_residual_stress_Pa": res_normal["residual_stress"],
        "elastic_degradation": not has_plasticity_high,
        "normal_yields": has_plasticity_normal,
        "all_checks_pass": (not has_plasticity_high and has_plasticity_normal),
    }


