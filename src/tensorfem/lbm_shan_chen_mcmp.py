def laplace_pressure_calibration(
    radii: list[float] | None = None,
    n: int = 128,
    g_ab: float = 5.0,
    rho_in: float = 1.4,
    rho_out: float = 0.2,
    steps: int = 8000,
    interface_width: float = 3.0,
    tau: float = 1.0,
) -> list[dict]:
    """Young-Laplace law calibration for the Shan-Chen MCMP model.

    For each droplet radius R, a circular drop of component ``a`` (density
    ``rho_in``) in component ``b`` (density ``rho_out``) is equilibrated.
    The pressure jump ΔP = P_inside - P_outside is measured from the
    thermodynamic EOS and compared with the Young-Laplace prediction
    ΔP = σ / R.

    The surface tension σ is estimated from the linear fit of ΔP vs 1/R.

    Parameters
    ----------
    radii : list of float
        Droplet radii to test (lattice units).  Default: [10, 15, 20, 25, 30].
    n : int
        Domain size (periodic square).
    g_ab : float
        Cross-interaction strength.
    rho_in, rho_out : float
        Dense / dilute phase densities for the initial condition.
    steps : int
        Equilibration steps per radius.
    interface_width : float
        Initial interface thickness (tanh profile).
    tau : float
        SRT relaxation time (both components).

    Returns
    -------
    results : list of dict
        One entry per radius with keys: radius, delta_P, spurious_current,
        rho_in_eq, rho_out_eq, P_inside, P_outside, mass_drift.
    """
    if radii is None:
        radii = [10.0, 15.0, 20.0, 25.0, 30.0]

    results = []
    for R in radii:
        cfg = MCMPConfig(
            nx=n, ny=n, tau_a=tau, tau_b=tau,
            g_aa=0.0, g_ab=g_ab, g_ba=g_ab, g_bb=0.0,
            rho0=1.0, psi_model="exp",
            velocity_mode="mass", neighbour_convention="plus",
            eq_shift="none", source_velocity="bary", force_scheme="guo",
        )
        sim = ShanChenMCMP(cfg)
        sim.init_drop(R, rho_in=rho_in, rho_out=rho_out,
                      interface_width=interface_width)

        mass_0 = sim.total_mass().copy()

        # Equilibrate
        for _ in range(steps):
            sim.step()

        rho = sim.density()
        P = sim.pressure_field(rho)

        # Radial averages
        r_bins, rho_a_avg = sim.radial_average(rho[0])
        r_bins, P_avg = sim.radial_average(P)

        # Identify inside/outside from the density profile
        # The interface is where rho_a drops from rho_in to rho_out
        mid_density = 0.5 * (rho_in + rho_out)
        interface_idx = np.argmin(np.abs(rho_a_avg - mid_density))
        interface_r = r_bins[interface_idx]

        # Inside: r < interface_r - margin; Outside: r > interface_r + margin
        margin = max(3, int(interface_width))
        inside_mask = r_bins < (interface_r - margin)
        outside_mask = r_bins > (interface_r + margin)

        if inside_mask.sum() == 0 or outside_mask.sum() == 0:
            # Fallback: use first/last bins
            inside_mask = r_bins < interface_r * 0.5
            outside_mask = r_bins > interface_r * 1.5

        P_inside = float(P_avg[inside_mask].mean()) if inside_mask.any() else float(P_avg[0])
        P_outside = float(P_avg[outside_mask].mean()) if outside_mask.any() else float(P_avg[-1])
        delta_P = P_inside - P_outside

        rho_in_eq = float(rho_a_avg[inside_mask].mean()) if inside_mask.any() else float(rho_a_avg[0])
        rho_out_eq = float(rho_a_avg[outside_mask].mean()) if outside_mask.any() else float(rho_a_avg[-1])

        sc = sim.spurious_current()
        mass_now = sim.total_mass()
        mass_drift = float(np.abs(mass_now - mass_0).max() / mass_0.max())

        results.append({
            "radius": R,
            "interface_radius": float(interface_r),
            "delta_P": delta_P,
            "P_inside": P_inside,
            "P_outside": P_outside,
            "rho_in_eq": rho_in_eq,
            "rho_out_eq": rho_out_eq,
            "spurious_current": sc,
            "mass_drift": mass_drift,
            "steps": steps,
            "r_bins": r_bins.tolist(),
            "rho_a_profile": rho_a_avg.tolist(),
            "P_profile": P_avg.tolist(),
        })

    # Estimate surface tension from linear fit: delta_P = sigma / R
    R_arr = np.array([r["radius"] for r in results])
    dP_arr = np.array([r["delta_P"] for r in results])
    # Fit delta_P = sigma * (1/R) => sigma = fit coefficient
    inv_R = 1.0 / R_arr
    sigma, _, _, _, _ = np.polyfit(inv_R, dP_arr, 1, full=True)
    # sigma is the slope; full=True returns [coefficients, residuals, rank, sv, rcond]
    # Actually np.polyfit returns coefficients; with full=True it returns extra info
    # Let me redo this properly
    coeffs = np.polyfit(inv_R, dP_arr, 1)
    sigma_est = coeffs[0]  # slope = sigma
    residuals = np.sum((dP_arr - (sigma_est * inv_R + coeffs[1])) ** 2)

    # Compute R^2
    ss_tot = np.sum((dP_arr - dP_arr.mean()) ** 2)
    r_squared = 1.0 - residuals / ss_tot if ss_tot > 0 else 0.0

    for r in results:
        r["sigma_estimated"] = float(sigma_est)
        r["r_squared"] = float(r_squared)
        r["laplace_predicted"] = float(sigma_est / r["radius"])
        r["laplace_error_pct"] = float(
            abs(r["delta_P"] - sigma_est / r["radius"]) / r["delta_P"] * 100
        ) if r["delta_P"] != 0 else float("inf")

    return results


