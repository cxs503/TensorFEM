"""Two-component Shan-Chen (MCMP) lattice-Boltzmann solver, D2Q9, float64.

This module is the fluid-side enabler of the ship platform's two-phase work
(phase separation, surface tension, cavitation nuclei, bubbly drag reduction).
It is a *from scratch* NumPy implementation of the model that the open-source
code ``lssfau/lbmpy`` exercises in

    tests/shan_chen/test_shan_chen_two_component.py

so the solver can be cross-validated (XVAL) against a published reference
solution instead of being trusted on inspection.

Model
-----
Two components ``s in {a, b}``, each with its own D2Q9 populations
``f_i^s`` and its own density ``rho_s``.  The physical model is

* exponential Shan-Chen pseudo potential

      psi_s = rho0 (1 - exp(-rho_s / rho0))

* cross interaction force (Shan & Chen 1993; Shan & Doolen 1996)

      F_s(x) = - psi_s(x) sum_{s'} g_{s s'} sum_i w_i c_i psi_{s'}(x + c_i)

  (``+ c_i`` -- the *plus* neighbour convention, see ``neighbour_convention``)

* one **barycentric** mixture velocity shared by both components

      u = ( sum_s [ sum_i c_i f_i^s + F_s / 2 ] ) / ( sum_s rho_s )

  which is the momentum of the mixture *including* the half force correction,
  so the equilibrium velocity must **not** be shifted a second time,

* Guo (2002) second-order forcing source, with the SRT relaxation frequency
  ``omega_s = 1 / tau_s``

      S_i^s = (1 - omega_s/2) w_i [ (c_i - u)/cs^2 + (c_i.u) c_i / cs^4 ] . F_s
      f_i^s(x + c_i, t+1) = f_i^s + omega_s (f_i^{eq}(rho_s, u) - f_i^s) + S_i^s

Two history notes are encoded as *switches* so that the earlier failure of
this anchor can be replayed instead of asserted (see
``MCMPConfig.neighbour_convention`` and ``MCMPConfig.eq_shift``); the defaults
are the validated settings.

Validation status
-----------------
``run_reference_case()`` reproduces the lbmpy reference case (64^2 periodic,
omega_a = omega_b = 1, g_ab = 6, 1000 steps, sharp step initial condition) to
``rel_L2 < 1e-6`` on the component-``a`` and component-``b`` density profiles,
i.e. seven orders of magnitude inside the 15 % acceptance band of the anchor
``XVAL-LBM-SHAN-CHEN-MCMP-BARYCENTRIC-GUO``.  See
``examples/lbm_shan_chen_mcmp_barycentric_guo_xval.py``.

References
----------
[1] Shan, X., Chen, H. (1993). Phys. Rev. E 47, 1815.
[2] Shan, X., Doolen, G. (1996). J. Stat. Phys. 81, 379 (MCMP, barycentric u).
[3] Guo, Z., Zheng, C., Shi, B. (2002). Phys. Fluids 14, 2007 (forcing).
[4] Krueger et al. (2017). The Lattice Boltzmann Method, sec. 9.3.
[5] lssfau/lbmpy, tests/shan_chen/test_shan_chen_two_component.py (reference
    array generated by lbm-principles-practice/chapter9/shanchen.cpp).
"""
