def equilibrium_d2q9(rho: np.ndarray, ux: np.ndarray, uy: np.ndarray) -> np.ndarray:
    """D2Q9 equilibrium ``w_i rho (1 + 3 c.u + 4.5 (c.u)^2 - 1.5 u^2)``."""
    cu = _CX * ux[None] + _CY * uy[None]
    usq = ux * ux + uy * uy
    return _W * rho[None] * (1.0 + 3.0 * cu + 4.5 * cu * cu - 1.5 * usq[None])


def psi_exponential(rho: np.ndarray, rho0: float = 1.0) -> np.ndarray:
    """Shan-Chen exponential pseudo potential ``rho0 (1 - exp(-rho/rho0))``."""
    return rho0 * (1.0 - np.exp(-np.asarray(rho, dtype=DTYPE) / rho0))


def psi_linear(rho: np.ndarray, rho0: float = 1.0) -> np.ndarray:
    """Linear pseudo potential ``psi = rho`` (legacy Shan-Chen form)."""
    return np.asarray(rho, dtype=DTYPE).copy()


@dataclass
class MCMPConfig:
    """Two-component Shan-Chen configuration (lattice units, ``dx = dt = 1``).

    Parameters
    ----------
    nx, ny : domain size (periodic in both directions)
    tau_a, tau_b : SRT relaxation times, ``omega_s = 1/tau_s``
    g_aa, g_ab, g_ba, g_bb : interaction matrix entries (attraction < 0 is
        *not* used here: the lbmpy convention takes the force as
        ``-psi_s sum g_ss' sum w c psi``, so ``g_ab > 0`` is attractive)
    rho0 : reference density of the pseudo potential
    psi_model : ``"exp"`` (validated) or ``"linear"``
    velocity_mode : ``"mass"`` (validated, equals lbmpy's ``u_bary``) or
        ``"tau"`` (viscosity weighted, identical while ``tau_a == tau_b``) or
        ``"self"`` (per-component velocity -- the scheme the anchor falsifies)
    neighbour_convention : ``"plus"`` (validated: ``psi(x + c_i)``) or
        ``"minus"`` (the defective ``psi(x - c_i)`` that flips the sign of the
        interaction force and diverges within ~30 steps at ``g_ab = 6``)
    eq_shift : ``"none"`` (validated: the barycentric velocity already contains
        ``(F_a + F_b)/2 / rho_tot``, so no per-component shift is applied) or
        ``"half"`` (adds ``F_s/(2 rho_s)`` again: double counting) or ``"tau"``
        (classic Shan-Chen ``tau F_s/rho_s`` shift)
    source_velocity : ``"bary"`` (validated) or ``"forced"`` (uses the shifted
        per-component velocity inside the Guo source term)
    force_scheme : ``"guo"`` (validated) or ``"none"`` (collision without the
        Guo source, for defect isolation only)
    """

    nx: int = 64
    ny: int = 64
    tau_a: float = 1.0
    tau_b: float = 1.0
    g_aa: float = 0.0
    g_ab: float = 6.0
    g_ba: float = 6.0
    g_bb: float = 0.0
    rho0: float = 1.0
    psi_model: str = "exp"
    velocity_mode: str = "mass"
    neighbour_convention: str = "plus"
    eq_shift: str = "none"
    source_velocity: str = "bary"
    force_scheme: str = "guo"

    def psi(self, rho: np.ndarray) -> np.ndarray:
        if self.psi_model == "exp":
            return psi_exponential(rho, self.rho0)
        if self.psi_model == "linear":
            return psi_linear(rho, self.rho0)
        raise ValueError(f"unknown psi_model {self.psi_model!r}")

    def g_matrix(self) -> np.ndarray:
        return np.array([[self.g_aa, self.g_ab],
                         [self.g_ba, self.g_bb]], dtype=DTYPE)


class ShanChenMCMP:
    """Periodic two-component Shan-Chen solver.

    State: ``f`` with shape ``(2, 9, ny, nx)`` (component, direction, y, x).
    """

    def __init__(self, cfg: MCMPConfig):
        self.cfg = cfg
        if cfg.tau_a <= 0.5 or cfg.tau_b <= 0.5:
            raise ValueError("tau must exceed 0.5 (positive viscosity)")
        if cfg.velocity_mode not in ("tau", "mass", "self"):
            raise ValueError(f"unknown velocity_mode {cfg.velocity_mode!r}")
        if cfg.neighbour_convention not in ("plus", "minus"):
            raise ValueError(f"unknown neighbour_convention {cfg.neighbour_convention!r}")
        if cfg.eq_shift not in ("none", "half", "tau"):
            raise ValueError(f"unknown eq_shift {cfg.eq_shift!r}")
        if cfg.source_velocity not in ("bary", "forced"):
            raise ValueError(f"unknown source_velocity {cfg.source_velocity!r}")
        if cfg.force_scheme not in ("guo", "none"):
            raise ValueError(f"unknown force_scheme {cfg.force_scheme!r}")
        self.nx, self.ny = cfg.nx, cfg.ny
        self.f = np.zeros((2, 9, cfg.ny, cfg.nx), dtype=DTYPE)
        self.t = 0
        self.tau = np.array([cfg.tau_a, cfg.tau_b], dtype=DTYPE)
        self.G = cfg.g_matrix()

    # ------------------------------------------------------------------ setup
    def init_uniform(self, rho_a: float, rho_b: float, ux=None, uy=None) -> None:
        """Initialise from uniform densities (equilibrium at rest by default)."""
        ny, nx = self.ny, self.nx
        ra = np.full((ny, nx), float(rho_a), dtype=DTYPE)
        rb = np.full((ny, nx), float(rho_b), dtype=DTYPE)
        ux = np.zeros((ny, nx), dtype=DTYPE) if ux is None else np.asarray(ux, DTYPE)
        uy = np.zeros((ny, nx), dtype=DTYPE) if uy is None else np.asarray(uy, DTYPE)
        self.f[0] = equilibrium_d2q9(ra, ux, uy)
        self.f[1] = equilibrium_d2q9(rb, ux, uy)
        self.t = 0

    def init_step_x(self, lo: float = 0.1, hi: float = 0.9) -> None:
        """Reference initial condition: a step in ``x`` at ``x = nx/2``.

        Component ``a`` is ``lo`` on the left half and ``hi`` on the right half,
        component ``b`` is the complement.  With periodicity this gives two
        interfaces (at ``x = nx-1|0`` and at ``nx/2-1|nx/2``), exactly as in the
        lbmpy reference case.
        """
        nx, ny = self.nx, self.ny
        half = nx // 2
        ra = np.empty((ny, nx), dtype=DTYPE)
        rb = np.empty((ny, nx), dtype=DTYPE)
        ra[:, :half] = lo
        ra[:, half:] = hi
        rb[:, :half] = hi
        rb[:, half:] = lo
        self.f[0] = equilibrium_d2q9(ra, np.zeros_like(ra), np.zeros_like(ra))
        self.f[1] = equilibrium_d2q9(rb, np.zeros_like(rb), np.zeros_like(rb))
        self.t = 0

    def init_drop(self, radius: float, rho_in: float = 0.9, rho_out: float = 0.1,
                  interface_width: float = 2.0) -> None:
        """Circular drop of component ``a`` (Laplace-law / spurious-current case)."""
        ny, nx = self.ny, self.nx
        yy, xx = np.meshgrid(np.arange(ny) + 0.5, np.arange(nx) + 0.5, indexing="ij")
        cx, cy = 0.5 * nx, 0.5 * ny
        r = np.sqrt((xx - cx) ** 2 + (yy - cy) ** 2)
        s = 0.5 * (1.0 - np.tanh(2.0 * (r - radius) / interface_width))  # 1 inside
        rho = np.empty((2, ny, nx), dtype=DTYPE)
        rho[0] = rho_out + (rho_in - rho_out) * s
        rho[1] = rho_in + (rho_out - rho_in) * s
        zero = np.zeros((ny, nx), dtype=DTYPE)
        for k in (0, 1):
            self.f[k] = equilibrium_d2q9(rho[k], zero, zero)
        self.t = 0

    # ------------------------------------------------------------- diagnostics
    def density(self) -> np.ndarray:
        """Component densities, shape ``(2, ny, nx)``."""
        return self.f.sum(axis=1)

    def raw_momentum(self) -> np.ndarray:
        """Raw momenta ``sum_i c_i f_i^s``, shape ``(2, 2, ny, nx)``."""
        mx = (self.f * _CX).sum(axis=1)
        my = (self.f * _CY).sum(axis=1)
        return np.stack((mx, my), axis=1)

    def interaction_force(self, rho: np.ndarray | None = None,
                          psi: np.ndarray | None = None) -> np.ndarray:
        """Shan-Chen interaction force, shape ``(2, 2, ny, nx)``.

        ``F_s(x) = - psi_s(x) sum_{s'} g_{s s'} sum_i w_i c_i psi_{s'}(x + c_i)``

        The shifted neighbour is taken with ``np.roll(psi, -c)`` because
        ``np.roll(a, s)[i] == a[i - s]``: rolling by ``-c`` therefore samples
        ``psi(x + c)``.  ``cfg.neighbour_convention="minus"`` keeps the
        defective variant of the first delivery for reproduction.
        """
        if rho is None:
            rho = self.density()
        if psi is None:
            psi = self.cfg.psi(rho)
        sign = -1 if self.cfg.neighbour_convention == "plus" else 1
        F = np.empty((2, 2, self.ny, self.nx), dtype=DTYPE)
        for s in (0, 1):
            acc_x = np.zeros((self.ny, self.nx), dtype=DTYPE)
            acc_y = np.zeros((self.ny, self.nx), dtype=DTYPE)
            for d in range(9):
                if CX[d] == 0 and CY[d] == 0:
                    continue
                nb = np.roll(np.roll(psi, sign * int(CY[d]), axis=1),
                             sign * int(CX[d]), axis=2)
                gpsi = self.G[s, 0] * nb[0] + self.G[s, 1] * nb[1]
                acc_x += (W9[d] * float(CX[d])) * gpsi
                acc_y += (W9[d] * float(CY[d])) * gpsi
            F[s, 0] = -psi[s] * acc_x
            F[s, 1] = -psi[s] * acc_y
        return F

    def barycentric_velocity(self, rho: np.ndarray | None = None,
                             m: np.ndarray | None = None,
                             F: np.ndarray | None = None) -> np.ndarray:
        """Mixture velocity, shape ``(2, ny, nx)`` (identical for both components).

        ``mode="mass"`` : ``u = sum_s (m_s + F_s/2) / sum_s rho_s``  (validated)
        ``mode="tau"``  : ``u = sum_s (m_s + F_s/2)/tau_s / sum_s rho_s/tau_s``
        ``mode="self"`` : per-component ``(m_s + F_s/2)/rho_s``
        """
        if rho is None:
            rho = self.density()
        if m is None:
            m = self.raw_momentum()
        if F is None:
            F = self.interaction_force(rho)
        num = m + 0.5 * F
        mode = self.cfg.velocity_mode
        if mode == "self":
            return num / rho[:, None]
        wgt = 1.0 / self.tau if mode == "tau" else np.ones(2)
        num_w = (num * wgt[:, None, None]).sum(axis=0)
        den = (rho * wgt[:, None, None]).sum(axis=0)
        u = num_w / den[None]
        return np.repeat(u[None], 2, axis=0)

    # ------------------------------------------------------------- evolution
    def step(self) -> None:
        """One full step: interaction force -> barycentric u -> collide -> stream."""
        cfg = self.cfg
        rho = self.density()
        m = self.raw_momentum()
        F = self.interaction_force(rho)
        u_bary = self.barycentric_velocity(rho, m, F)
        if cfg.eq_shift == "none":
            shift = 0.0
        elif cfg.eq_shift == "half":
            shift = 0.5
        elif cfg.eq_shift == "tau":
            shift = 1.0  # multiplied by tau below
        else:  # pragma: no cover - guarded in __init__
            raise ValueError(f"unknown eq_shift {cfg.eq_shift!r}")
        if cfg.eq_shift == "tau":
            u_forced = u_bary + (self.tau[:, None, None] * F) / rho[:, None]
        else:
            u_forced = u_bary + shift * F / rho[:, None]

        f_new = np.empty_like(self.f)
        for s in (0, 1):
            tau = self.tau[s]
            omega = 1.0 / tau
            ux, uy = u_forced[s, 0], u_forced[s, 1]
            feq = equilibrium_d2q9(rho[s], ux, uy)
            out = self.f[s] + omega * (feq - self.f[s])
            if cfg.force_scheme == "guo":
                if cfg.source_velocity == "bary":
                    sx, sy = u_bary[s, 0], u_bary[s, 1]
                else:
                    sx, sy = ux, uy
                cu = _CX * sx[None] + _CY * sy[None]
                cF = _CX * F[s, 0][None] + _CY * F[s, 1][None]
                uF = (sx * F[s, 0] + sy * F[s, 1])[None]
                src = _W * (3.0 * (cF - uF) + 9.0 * cu * cF)
                out += (1.0 - 0.5 * omega) * src
            for d in range(9):
                f_new[s, d] = np.roll(np.roll(out[d], int(CY[d]), axis=0),
                                      int(CX[d]), axis=1)
        self.f = f_new
        self.t += 1

    def run(self, steps: int, callback=None) -> None:
        for _ in range(steps):
            self.step()
            if callback is not None:
                callback(self)

    # ------------------------------------------------------------- observables
    def velocity(self) -> np.ndarray:
        """Barycentric velocity at the current state, shape ``(2, ny, nx)``."""
        rho = self.density()
        F = self.interaction_force(rho)
        return self.barycentric_velocity(rho, None, F).mean(axis=0)

    def spurious_current(self) -> float:
        """``max |u|`` over the domain (spurious current of a static drop)."""
        u = self.velocity()
        return float(np.sqrt(u[0] ** 2 + u[1] ** 2).max())

    def total_mass(self) -> np.ndarray:
        """Integrated component masses, shape ``(2,)``."""
        return self.density().sum(axis=(1, 2))

    def profile_x(self, component: int = 0, y: int = 0) -> np.ndarray:
        """Density of one component along ``x`` on row ``y``."""
        return self.density()[component, y, :]


