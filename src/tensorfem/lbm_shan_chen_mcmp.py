def shan_chen_mcmp_evidence() -> list:
    """Registered benchmark evidence for the two-phase (MCMP) capability.

    Cheap case (32 x 32, 400 steps, ``g_ab = 6``) against a *live generated*
    lbmpy reference stored in ``docs/assets/.../lbmpy_32x32_g6_400step.json``;
    the published 64 x 64 / 1000-step anchor case is run by
    ``examples/lbm_shan_chen_mcmp_barycentric_guo_xval.py``.
    """
    from .benchmark_registry import _evidence

    if not GOLDEN_32x32.exists():  # pragma: no cover - artifact ships with the repo
        raise FileNotFoundError(
            f"{GOLDEN_32x32} missing; regenerate with "
            "python tools/lbmpy_shan_chen_live_ref.py --n 32 --steps 400 "
            f"--out {GOLDEN_32x32}")
    golden = json.loads(GOLDEN_32x32.read_text())
    n = int(golden["params"]["n"])
    steps = int(golden["params"]["steps"])
    g_ab = float(golden["params"]["g_ab"])
    sim = ShanChenMCMP(MCMPConfig(nx=n, ny=n, g_ab=g_ab, g_ba=g_ab,
                                  tau_a=1.0, tau_b=1.0))
    sim.init_step_x(0.1, 0.9)
    sim.run(steps)
    got = sim.density()[0, 0, :]
    ref = np.asarray(golden["rho_a_profile"], dtype=DTYPE)
    peak = int(np.argmax(ref))
    rows = [
        _evidence(
            "lbm.mcmp_shan_chen.interface_density",
            "two-component Shan-Chen LBM",
            f"component-a density at the periodic interface (x=0) after {steps} steps",
            "-",
            "lssfau/lbmpy shan-chen two-component algorithm executed live by "
            f"tools/lbmpy_shan_chen_live_ref.py (n={n}, g_ab={g_ab}, {steps} "
            "steps); tensorfem.lbm_shan_chen_mcmp reproduces it",
            float(got[0]), float(ref[0]), tolerance=0.005),
        _evidence(
            "lbm.mcmp_shan_chen.dense_peak_density",
            "two-component Shan-Chen LBM",
            f"component-a density peak after {steps} steps",
            "-",
            "same live lbmpy reference case as lbm.mcmp_shan_chen.interface_density",
            float(got[peak]), float(ref[peak]), tolerance=0.005),
        _evidence(
            "lbm.mcmp_shan_chen.total_mass_a",
            "two-component Shan-Chen LBM",
            "conserved mass of component a (sum of densities)",
            "-",
            "mass conservation of the collision + periodic streaming operators "
            "(analytic invariant, initial mass 0.5 * n^2)",
            float(sim.total_mass()[0]), 0.5 * n * n, tolerance=0.0001),
    ]
    return rows