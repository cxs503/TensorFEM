def test_least_squares_recovers_known_coefficients(module):
    x = np.linspace(0.02, 0.25, 8)
    e = -0.0007 - 0.104 * x + 0.759 * x ** 2
    fit = module.least_squares(x, e, (0, 1, 2))
    assert fit["max_abs_residual"] < 1e-15
    for got, want in zip(fit["coefficients"], (-0.0007, -0.104, 0.759)):
        assert abs(got - want) < 1e-10


def test_q8_face_load_gives_a_pure_couple(module):
    """Own Q8 load vector: zero net axial force, resultant moment exactly M."""
    from tensorfem.hex20 import structured_hex20_mesh

    nodes, elements = structured_hex20_mesh(0.05, module.BD, module.HD, 2, 2, 2)
    f = module.face_load_vector(
        nodes, elements, 2, 2, 2,
        lambda y, z: np.array([module.MOMENT * (z - 0.5 * module.HD) / module.INERTIA, 0.0, 0.0]),
    )
    tip, _ = module._face_nodes(nodes, 0.05)
    coords = nodes.numpy()
    assert abs(float(f[0::3][tip].sum())) < 1e-10
    assert abs(float((f[0::3][tip] * coords[tip, 2]).sum()) - module.MOMENT) < 1e-12


def test_q8_shape_functions_partition_of_unity(module):
    for s, t in ((-1.0, -1.0), (0.0, 0.0), (0.37, -0.62), (1.0, 1.0)):
        n, _ = module._q8(s, t)
        assert math.isclose(float(n.sum()), 1.0, abs_tol=1e-14)


def test_gap_coefficient_matches_the_timoshenko_gap(module):
    assert math.isclose(module.GAP, 0.78, rel_tol=1e-12)
    assert math.isclose(module.delta_ti(1.0) - module.delta_eb(1.0),
                        module.P * 1.0 / (module.KAPPA * module.G * module.AREA), rel_tol=1e-12)
