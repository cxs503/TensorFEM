"""Fail-closed tests for the lateral-surface torsion peak recovery."""
from __future__ import annotations

import json
from pathlib import Path

import pytest
import torch

from tensorfem.torsion_bar import (max_shear_stress, rectangular_torsion_constant,
                                   torsion_shear_stress)
from tensorfem.torsion_boundary import torsion_boundary_peak

SIDE, YOUNG, POISSON, TORQUE = 1.0, 1.0e9, 0.3, 1.0
ROOT = Path(__file__).resolve().parents[1]


def _exact_peak(twist_rate: float, terms: int = 401) -> float:
    shear = YOUNG / (2.0 * (1.0 + POISSON))
    tx, ty = torsion_shear_stress(torch.tensor([SIDE / 2.0]), torch.tensor([0.0]),
                                  SIDE, SIDE, twist_rate=twist_rate, shear_modulus=shear,
                                  terms=terms)
    return float(torch.sqrt(tx ** 2 + ty ** 2))


def test_reference_matches_classical_torsion_coefficient():
    """The square-section torsion constant must reproduce the textbook 0.1406."""
    j = rectangular_torsion_constant(SIDE, SIDE)
    assert j == pytest.approx(0.1406, abs=5e-5)


def test_boundary_series_agrees_with_interior_scan():
    """Surface series value vs the interior grid scan (a strict lower bound)."""
    shear = YOUNG / (2.0 * (1.0 + POISSON))
    theta = TORQUE / (shear * rectangular_torsion_constant(SIDE, SIDE))
    boundary = _exact_peak(theta)
    scan, location = max_shear_stress(SIDE, SIDE, torque=TORQUE)
    # The scan sits half a cell inside the surface, at the long-side midpoint.
    assert scan < boundary
    assert abs(location[0]) > 0.49 and abs(location[1]) < 1e-9
    assert (boundary - scan) / boundary < 0.01


def test_surface_peak_brackets_the_interior_field():
    """|tau| must be largest on the lateral surface, not in the interior."""
    theta = TORQUE / (YOUNG / (2.0 * (1.0 + POISSON)) * rectangular_torsion_constant(SIDE, SIDE))
    boundary = _exact_peak(theta)
    interior = _exact_peak(theta * 0.0 + theta)  # same scale, interior point below
    shear = YOUNG / (2.0 * (1.0 + POISSON))
    tx, ty = torsion_shear_stress(torch.tensor([0.0]), torch.tensor([0.0]), SIDE, SIDE,
                                  twist_rate=theta, shear_modulus=shear)
    assert float(torch.sqrt(tx ** 2 + ty ** 2)) < 1e-9
    assert interior == pytest.approx(boundary)


def test_centroid_sampling_cannot_reach_the_peak():
    """The previously WITHHELD metric stays far outside the gate: that is the gap."""
    coarse = torsion_boundary_peak(element="hex8", segments=4)
    assert coarse.error_centroid > 0.20
    assert coarse.error_direct < coarse.error_centroid


def test_surface_recovery_qualifies_and_coarse_mesh_fails_closed():
    qualified = torsion_boundary_peak(element="hex8", segments=6)
    assert qualified.error_direct < 0.03
    assert qualified.error_direct < qualified.error_centroid
    coarse = torsion_boundary_peak(element="hex8", segments=2)
    assert coarse.error_direct > 0.03


def test_hex20_surface_recovery_qualifies():
    quadratic = torsion_boundary_peak(element="hex20", segments=4)
    assert quadratic.error_extrapolated < 0.03
    assert quadratic.twist_rate_relative_error < 0.01
    # the coarse 2x20 mesh overshoots the peak and is retained, not tuned away
    coarse = torsion_boundary_peak(element="hex20", segments=2)
    assert coarse.error_direct > 0.10


def test_invalid_arguments_rejected():
    with pytest.raises(ValueError):
        torsion_boundary_peak(element="tet4", segments=2)
    with pytest.raises(ValueError):
        torsion_boundary_peak(element="hex8", segments=0)


def test_evidence_file_consistent_with_code():
    path = ROOT / "docs" / "assets" / "torsion_boundary_stress" / "boundary_peak_evidence.json"
    if not path.exists():  # evidence is generated by the benchmark script
        pytest.skip("evidence file not generated in this checkout")
    payload = json.loads(path.read_text())
    status = payload["status"]
    assert status["peak_gate_pct"] == 3.0
    assert status["surface_direct_qualified"] is True
    assert status["centroid_never_qualified"] is True
    assert status["coarse_fail_retained"] is True
    for row in payload["ladder"]:
        assert row["surface_direct_peak"] > 0.0
        assert row["surface_extrapolated_peak"] > 0.0
    finest = max(payload["ladder"], key=lambda r: r["n_dofs"])
    assert finest["reference_boundary_peak"] > 0.99 * finest["reference_scan_peak"]