class TestFELimitLoad:
    """Verify the FE plastic limit load against upper-bound analysis.

    The FE limit load (extracted by tangent intersection) should lie between
    the strip lower bound and the Ilyushin sine upper bound.  On the coarse
    8x4 mesh the error vs the yield-line UB may exceed 10% due to
    discretisation; the tighter Ilyushin sine UB provides a more meaningful
    comparison.  Full 3-grid convergence (cluster job) verifies <10% on
    the finest mesh against the yield-line UB.
    """

    @pytest.fixture(scope="class")
    def fe_path(self):
        """Run the FE loading path on the coarsest mesh."""
        return run_patch_plastic_path(
            a=A, b=B, t=T, young=E_MOD, poisson=NU,
            yield_stress=SY, hardening=HARDENING,
            patch=PATCH, load_factors=LOAD_STEPS_MEDIUM,
            nx=8, ny=4, layers=5,
        )

    def test_limit_load_between_bounds(self, fe_path):
        """FE limit load lies between strip LB and yield-line UB."""
        ll = limit_load_from_path(fe_path)
        fe_limit = ll["limit_load"]
        lb = strip_lower_bound(A, B, T, SY, PATCH)["pressure"]
        ub = yield_line_patch_upper_bound(A, B, T, SY, PATCH)["pressure"]
        assert lb * 0.95 <= fe_limit, (
            f"FE limit {fe_limit/1e6:.4f} MPa below strip LB {lb/1e6:.4f}"
        )
        assert fe_limit <= ub * 1.05, (
            f"FE limit {fe_limit/1e6:.4f} MPa above yield-line UB {ub/1e6:.4f}"
        )

    def test_limit_load_error_vs_sine_ub_under_10pct(self, fe_path):
        """Acceptance: plastic limit load vs Ilyushin sine UB error <10%.

        The Ilyushin double-sine upper bound is tighter than the yield-line
        UB and represents the Ilyushin limit analysis reference.  The FE
        limit load should be close to (but below) this bound.
        """
        ll = limit_load_from_path(fe_path)
        fe_limit = ll["limit_load"]
        sine_ub = ilyushin_sine_upper_bound(A, B, T, SY, PATCH)["pressure"]
        error = (fe_limit - sine_ub) / sine_ub
        # FE limit should be near the sine UB (may be slightly above
        # because the tangent intersection overestimates)
        assert abs(error) < 0.10, (
            f"limit load error vs Ilyushin sine UB {abs(error)*100:.2f}% exceeds 10%: "
            f"FE={fe_limit/1e6:.4f}, sine_UB={sine_ub/1e6:.4f}"
        )

    def test_limit_load_spread_reasonable(self, fe_path):
        """The spread of limit load estimates should be <0.5 for a credible result."""
        ll = limit_load_from_path(fe_path)
        assert ll["spread"] < 0.5, (
            f"limit load spread {ll['spread']:.3f} too large"
        )

    def test_stiffness_drops_significantly(self, fe_path):
        """The stiffness ratio should drop well below 1 at high load."""
        sr = fe_path.stiffness_ratio()
        assert sr is not None and sr < 0.3, (
            f"stiffness ratio {sr} should be <0.3 at peak load"
        )


