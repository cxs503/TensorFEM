# Low-temperature steel integration with FE
# ===================================================================

class TestLowTempSteelFE:
    """Verify that the low-temperature flow stress model integrates with the FE."""

    def test_dh36_minus40_higher_yield_than_20c(self):
        """DH36 at -40C has higher yield stress, so first yield occurs at higher pressure."""
        fy_20 = analytic_first_yield_pressure(A, B, T, E_MOD, NU, 355e6, PATCH)["pressure"]
        flow = low_temperature_flow_stress("DH36", -40.0)
        fy_m40 = analytic_first_yield_pressure(A, B, T, E_MOD, NU, flow.yield_stress, PATCH)["pressure"]
        assert fy_m40 > fy_20, (
            f"first yield at -40C ({fy_m40/1e6:.4f} MPa) should exceed "
            f"that at 20C ({fy_20/1e6:.4f} MPa)"
        )

    def test_below_dbtt_no_plastic_result(self):
        """Below DBTT, the capacity summary withholds the plastic result."""
        summary = plate_capacity_summary(
            a=A, b=B, t=T, young=E_MOD, poisson=NU,
            grade="DH36", temperature_c=-70.0,  # below DBTT (-65C)
            patch=PATCH, hardening=HARDENING,
            load_factors=[0.5e6],
            nx=8, ny=4, layers=5,
        )
        assert summary["fe"] is None, (
            "FE plastic result should be withheld below DBTT"
        )
        assert "below DBTT" in summary["evidence"]


