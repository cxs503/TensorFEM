class TestPermanentDeflection:
    """Verify permanent deflection post-processing after unloading."""

    @pytest.fixture(scope="class")
    def unloaded_path(self):
        """Run loading + unloading on the coarsest mesh."""
        return run_patch_plastic_path(
            a=A, b=B, t=T, young=E_MOD, poisson=NU,
            yield_stress=SY, hardening=HARDENING,
            patch=PATCH, load_factors=[0.5e6, 1.0e6, 1.5e6],
            nx=8, ny=4, layers=5,
            unload_steps=5,
        )

    def test_permanent_deflection_positive(self, unloaded_path):
        """Permanent deflection is positive after plastic deformation."""
        assert unloaded_path.permanent_deflection is not None, (
            "permanent deflection not computed"
        )
        assert unloaded_path.permanent_deflection > 0, (
            f"permanent deflection {unloaded_path.permanent_deflection} should be positive"
        )

    def test_permanent_deflection_less_than_peak(self, unloaded_path):
        """Permanent deflection is less than peak deflection."""
        peak = unloaded_path.loading[-1].centre_deflection
        perm = unloaded_path.permanent_deflection
        assert perm < peak, (
            f"permanent {perm:.6f} should be less than peak {peak:.6f}"
        )

    def test_permanent_set_valid(self, unloaded_path):
        """The permanent set is valid (unloading converged)."""
        assert unloaded_path.permanent_set_valid, (
            f"permanent set invalid: {unloaded_path.unload_failure}"
        )

    def test_unloading_reduces_deflection(self, unloaded_path):
        """Each unloading step reduces the deflection."""
        for i in range(1, len(unloaded_path.unloading)):
            prev = unloaded_path.unloading[i - 1].centre_deflection
            curr = unloaded_path.unloading[i].centre_deflection
            assert curr <= prev + 1e-12, (
                f"deflection increased during unloading: {prev:.6f} -> {curr:.6f}"
            )

    def test_permanent_deflection_scales_with_plastic_strain(self, unloaded_path):
        """Permanent deflection is correlated with plastic strain (alpha > 0)."""
        peak_alpha = unloaded_path.loading[-1].max_alpha
        perm = unloaded_path.permanent_deflection
        assert peak_alpha > 0, "no plastic strain at peak"
        assert perm > 0, "no permanent deflection despite plastic strain"


