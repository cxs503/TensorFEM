# Consistency regression: elastic FE matches Navier on same mesh
# ===================================================================

class TestElasticConsistency:
    """Verify that the FE elastic solution is consistent with Navier on the same mesh.

    This is the 'consistency regression against the elastic solution on the
    same mesh' required by the anchor acceptance criteria.
    """

    def test_elastic_deflection_matches_navier(self):
        """FE centre deflection at low load matches Navier within 5%."""
        fy = analytic_first_yield_pressure(A, B, T, E_MOD, NU, SY, PATCH)["pressure"]
        p_test = 0.25 * fy
        path = run_patch_plastic_path(
            a=A, b=B, t=T, young=E_MOD, poisson=NU,
            yield_stress=SY, hardening=HARDENING,
            patch=PATCH, load_factors=[p_test],
            nx=8, ny=4, layers=5,
        )
        fe_w = path.loading[0].centre_deflection
        navier = elastic_patch_plate(A, B, T, E_MOD, NU, PATCH, p_test)
        navier_w = navier["deflection"][0]
        error = abs(fe_w - navier_w) / navier_w
        assert error < 0.05, (
            f"elastic deflection error {error*100:.2f}%: "
            f"FE={fe_w:.6f}, Navier={navier_w:.6f}"
        )

    def test_elastic_linearity_in_fe(self):
        """FE response is linear in the elastic range."""
        fy = analytic_first_yield_pressure(A, B, T, E_MOD, NU, SY, PATCH)["pressure"]
        p1, p2 = 0.1 * fy, 0.2 * fy
        path1 = run_patch_plastic_path(
            a=A, b=B, t=T, young=E_MOD, poisson=NU,
            yield_stress=SY, hardening=HARDENING,
            patch=PATCH, load_factors=[p1],
            nx=8, ny=4, layers=5,
        )
        path2 = run_patch_plastic_path(
            a=A, b=B, t=T, young=E_MOD, poisson=NU,
            yield_stress=SY, hardening=HARDENING,
            patch=PATCH, load_factors=[p2],
            nx=8, ny=4, layers=5,
        )
        w1 = path1.loading[0].centre_deflection
        w2 = path2.loading[0].centre_deflection
        ratio = w2 / w1
        assert abs(ratio - 2.0) < 0.01, (
            f"elastic linearity ratio {ratio:.4f} should be 2.0"
        )

    def test_no_plastic_strain_below_yield(self):
        """No plastic strain accumulates below the first-yield pressure."""
        fy = analytic_first_yield_pressure(A, B, T, E_MOD, NU, SY, PATCH)["pressure"]
        path = run_patch_plastic_path(
            a=A, b=B, t=T, young=E_MOD, poisson=NU,
            yield_stress=SY, hardening=HARDENING,
            patch=PATCH, load_factors=[0.5 * fy, 0.8 * fy],
            nx=8, ny=4, layers=5,
        )
        for step in path.loading:
            assert step.max_alpha < 1e-12, (
                f"plastic strain {step.max_alpha:.2e} at p={step.load_factor/1e6:.4f} MPa "
                f"below first yield {fy/1e6:.4f} MPa"
            )


