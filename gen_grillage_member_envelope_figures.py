"""Figures + programmatic tables for the round-5 member load-path envelope.

Reads ``artifacts/grillage_member_envelope/*.json`` (written by
``benchmarks/grillage_member_envelope_round5.py``) and writes

* ``docs/assets/grillage_member_envelope/fig_frame_utilisation.png``
* ``docs/assets/grillage_member_envelope/fig_uniform_defect.png``
* ``docs/assets/grillage_member_envelope/fig_belt_and_classical.png``
* ``docs/grillage_member_envelope_tables.md``  (markdown injected from JSON)

No number in the markdown is typed by hand.
"""
from __future__ import annotations

import json
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

ART = Path("artifacts/grillage_member_envelope")
FIG = Path("docs/assets/grillage_member_envelope")
TABLES = Path("docs/grillage_member_envelope_tables.md")


def _load(name):
    return json.loads((ART / name).read_text(encoding="utf-8"))


def figure_frame(rows) -> None:
    labels = [f"{r['n_spans']}sp/{r['patch_length_m']:.2f}m" for r in rows]
    smeared = [r["smeared_u_frame"] for r in rows]
    system = [r["system_u_frame"] for r in rows]
    envelope = [r["envelope_u_frame"] for r in rows]
    x = range(len(rows))
    fig, ax = plt.subplots(figsize=(8, 4.2), dpi=140)
    w = 0.27
    ax.bar([i - w for i in x], smeared, w, label="smeared (legacy)", color="#c0392b")
    ax.bar(list(x), system, w, label="system (discrete grillage)", color="#2471a3")
    ax.bar([i + w for i in x], envelope, w, label="envelope (panel branch)", color="#7d8c8e")
    ax.axhline(1.0, color="k", lw=0.8, ls="--")
    ax.set_xticks(list(x))
    ax.set_xticklabels(labels, rotation=30, ha="right", fontsize=8)
    ax.set_ylabel("frame utilisation $U_{frame}$ at $p_{ice}=6$ MPa")
    ax.set_title("Transverse frame demand: position-blind share vs load-path branches")
    ax.legend(fontsize=8)
    fig.tight_layout()
    fig.savefig(FIG / "fig_frame_utilisation.png")
    plt.close(fig)


def figure_uniform(uniform) -> None:
    fig, ax = plt.subplots(figsize=(5.2, 3.8), dpi=140)
    names = ["classical\n$p a L^2/8$", "system\n(discrete grid)", "smeared\n(legacy)"]
    vals = [uniform["analytic_frame_moment_kNm"], uniform["system_frame_moment_kNm"],
            uniform["analytic_frame_moment_kNm"] * uniform["smeared_over_system"]]
    bars = ax.bar(names, vals, color=["#117a65", "#2471a3", "#c0392b"])
    ax.set_yscale("log")
    ax.set_ylabel("frame moment at $p_h=0.1$ MPa [kN m]")
    ax.set_title("Uniform lateral pressure: the legacy layer under-reports by "
                 f"{1/uniform['smeared_over_system']:.0f}x")
    for b, v in zip(bars, vals):
        ax.text(b.get_x() + b.get_width() / 2, v * 1.15, f"{v:.1f}", ha="center", fontsize=8)
    fig.tight_layout()
    fig.savefig(FIG / "fig_uniform_defect.png")
    plt.close(fig)


def figure_belt(belt, classical) -> None:
    fig, ax = plt.subplots(figsize=(5.6, 3.8), dpi=140)
    names = ["panel simple\nspan", "system\n(belt loaded)"]
    vals = [belt["panel_simple_span_moment_kNm"], belt["belt_stiffener_moment_kNm"]]
    ax.bar(names, vals, color=["#b7950b", "#2471a3"])
    ax.set_ylabel("stiffener moment at 1 MPa [kN m]")
    ax.set_title(f"Ice-belt loading reserve: panel/system = {belt['panel_over_system']:.2f}")
    for i, v in enumerate(vals):
        ax.text(i, v * 1.02, f"{v:.1f}", ha="center", fontsize=8)
    ax.text(0.02, 0.95,
            f"plate $p_{{ult}}$ = {classical['model_p_ult']/1e6:.3f} MPa\n"
            f"classical SS strip = {classical['reference_ss_strip_first_hinge']/1e6:.3f} MPa\n"
            f"error = {100*classical['relative_error_vs_ss_strip']:+.2f} %",
            transform=ax.transAxes, fontsize=8, va="top")
    fig.tight_layout()
    fig.savefig(FIG / "fig_belt_and_classical.png")
    plt.close(fig)


def tables(rows, combined, uniform, belt, classical, bracket, gates) -> None:
    lines = ["<!-- generated by gen_grillage_member_envelope_figures.py: do not edit -->",
             "", "## Sweep: member demands at $p_{ice}$ = 6 MPa", "",
             "| n_spans | patch position | patch [m] | U_frame smeared | U_frame system | U_frame envelope | smeared/system | U_stiff smeared | U_stiff system | U_stiff envelope |",
             "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for r in rows:
        lines.append("| {n_spans} | {pos} | {lx:.2f} x 0.35 | {sf:.4f} | {su:.4f} | {ef:.4f} | {ra:.2f}x | {ss:.3f} | {su2:.3f} | {es:.3f} |".format(
            n_spans=r["n_spans"], pos=r["patch_position"], lx=r["patch_length_m"],
            sf=r["smeared_u_frame"], su=r["system_u_frame"], ef=r["envelope_u_frame"],
            ra=r["smeared_over_system_frame"], ss=r["smeared_u_stiffener"],
            su2=r["system_u_stiffener"], es=r["envelope_u_stiffener"]))
    lines += ["", "## Acceptance combined cases under each member model", "",
              "| case | $\\sigma_x/\\sigma_y$ | patch [m] | $p_h$ [MPa] | model | $p_{ice,ult}$ [MPa] | governing | U_plate | U_stiff | U_frame |",
              "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for row in combined:
        for model in ("smeared", "system", "panel"):
            d = row[model]
            lines.append("| {lab} | {eta:.2f} | {p} | {ph:.2f} | {m} | {pu:.3f} | {g} | {up:.3f} | {us:.3f} | {uf:.3f} |".format(
                lab=row["label"], eta=row["eta"], p=row["patch_m"],
                ph=row["hydrostatic_MPa"], m=model, pu=d["p_ult_MPa"],
                g=d["governing"], up=d["u_plate"], us=d["u_stiffener"], uf=d["u_frame"]))
    lines += ["", "## Uniform-pressure (hydrostatic) check", "",
              "| quantity | value |", "| --- | --- |",
              f"| classical frame moment $p a L^2/8$ | {uniform['analytic_frame_moment_kNm']:.2f} kN m |",
              f"| system (discrete grid) | {uniform['system_frame_moment_kNm']:.2f} kN m |",
              f"| system vs classical | {100*uniform['system_vs_analytic_rel']:+.2f} % |",
              f"| smeared frame utilisation / system | {uniform['smeared_over_system']:.4f} (defect: legacy under-reports) |",
              "", "## Ice-belt loading reserve", "",
              f"| panel simple span | {belt['panel_simple_span_moment_kNm']:.2f} kN m |",
              f"| system, belt loaded | {belt['belt_stiffener_moment_kNm']:.2f} kN m |",
              f"| panel/system | {belt['panel_over_system']:.2f} |",
              "", "## Classical plate bracket (literature comparison)", "",
              "| quantity | value |", "| --- | --- |",
              f"| $M_p = \\sigma_y t^2/4$ | {bracket['plate_plastic_moment_per_width']:.0f} N m/m |",
              f"| panel short span b | {bracket['panel_short_span']:.3f} m (aspect {bracket['panel_aspect']:.1f}) |",
              f"| classical SSSS strip first hinge $8M_p/b^2$ | {bracket['p_first_hinge_ss_strip']/1e6:.4f} MPa |",
              f"| classical clamped strip plastic collapse $16M_p/b^2$ | {bracket['p_plastic_collapse_clamped_strip']/1e6:.4f} MPa |",
              f"| model $p_{{ult}}$ (plate governed) | {classical['model_p_ult']/1e6:.4f} MPa |",
              f"| error vs SSSS strip | {100*classical['relative_error_vs_ss_strip']:+.2f} % |",
              "", "## Gates", "", "| gate | value | reference | pass |", "| --- | --- | --- | --- |"]
    for g in gates:
        lines.append("| {g} | {v} | {r} | {p} |".format(
            g=g["gate"], v=g["value"], r=g["reference"], p="PASS" if g["passed"] else "FAIL"))
    TABLES.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    FIG.mkdir(parents=True, exist_ok=True)
    rows = _load("sweep.json")
    combined = _load("combined_cases.json")
    summary = _load("summary.json")
    uniform = summary["uniform_load"]
    belt = summary["belt"]
    classical = summary["classical"]
    bracket = summary["bracket"]
    gates = summary["gates"]
    figure_frame(rows)
    figure_uniform(uniform)
    figure_belt(belt, classical)
    tables(rows, combined, uniform, belt, classical, bracket, gates)
    print("figures + tables written")


if __name__ == "__main__":
    main()